const OrcaConfigKey *find_orca_config_key(const std::string &key)
{
    const OrcaConfigKey *first = std::begin(k_orca_config_keys);
    const OrcaConfigKey *last  = std::end(k_orca_config_keys);
    while (first < last) {
        const OrcaConfigKey *middle = first + (last - first) / 2;
        const int            order  = std::strcmp(key.c_str(), middle->key);
        if (order == 0)
            return middle;
        if (order < 0)
            last = middle;
        else
            first = middle + 1;
    }
    return nullptr;
}

size_t orca_config_key_count() { return std::size(k_orca_config_keys); }

// Return borrowed immutable static storage for the complete sorted array; callers use the published count,
// retain no ownership, and no allocation or failure is possible.
const OrcaConfigKey *orca_config_keys() { return k_orca_config_keys; }

