// Borrow print/plan views, copy validated catalog metadata and initialize export
// state; return owned preamble text with definitions for real instances only,
// retaining their plan IDs. The text holds G-code only: the file header, notes and
// thumbnails belong to the exporter. Invalid metadata throws; no ownership of the
// borrowed views is retained.
std::string DefaultGCodeFirmwareSession::begin_print(const Print &print, const ConstPrintingPlan &plan)
{
    setup(print.config());
    m_object_labels.clear();
    m_current_printing_catalog_id = uint32_t(-1);
    m_seen_object_group = false;
    m_object_labels.reserve(plan.object_instance_count());
    std::vector<ObjectLabel> real_labels;
    for (uint32_t id = 0; id < plan.object_instance_count(); ++id) {
        const PrintingObjectInstance instance = plan.object_instance(id);
        if (instance.id() != id || instance.name().empty() ||
            !instance.has_projected_outline())
            throw std::invalid_argument("The PrintingPlan contains an invalid canonical object instance.");
        if (instance.has_object()) {
            const Object object = instance.object();
            if (!object.valid() || instance.object_instance_idx() >= object.instance_count())
                throw std::invalid_argument("The PrintingPlan contains an invalid source object instance.");
        }
        const Polygon outline = instance.projected_outline();
        ObjectLabel label;
        label.id = id;
        label.is_synthetic = !instance.has_object();
        label.name = instance.name();
        label.projected_outline_center = instance.projected_outline_center();
        label.projected_outline.reserve(outline.size());
        for (uint32_t point_idx = 0; point_idx < outline.size(); ++point_idx)
            label.projected_outline.push_back(outline[point_idx]);
        if (!label.is_synthetic)
            real_labels.push_back(label);
        m_object_labels.push_back(std::move(label));
    }
    const bool firmware_labels = m_object_label_style == ObjectLabelStyle::Firmware ||
        m_object_label_style == ObjectLabelStyle::Both;
    return (firmware_labels ? encode_object_definitions(real_labels) : std::string()) +
        m_preamble->begin(print, plan);
}

// Inspect a borrowed plan group, increment the sequential object index for later real objects, and return any required start travel; an uninitialized session throws and the group remains unowned.
std::string DefaultGCodeFirmwareSession::begin_group(const ConstPrintingGroup &group)
{
    if (!m_is_setup)
        throw std::logic_error("The firmware session was not initialized by begin_print().");
    // Ordering represents a sequential object as a group with exactly one
    // source instance. Auxiliary groups carry none, while layer-wise plans may
    // carry several. Skipping both keeps ordinary first-path travel unchanged.
    if (group.object_instance_count() != 1)
        return {};
    if (!m_seen_object_group) {
        m_seen_object_group = true;
        return {};
    }
    ++m_current_object_idx;
    return move_to_group_start(group);
}

// Borrow a valid layer group, validate its listed source heights and calculate
// the Z gap once. Return owned layer markers using the listed maximum or that
// gap, forget the cached extrusion marker so the first printable extrusion
// writes ;HEIGHT: again, set script height from the first source extrusion or
// the same gap, and advance state without retaining the view. An uninitialized
// session or non-positive source height throws before state changes; a
// non-rising source-free Z may still produce a non-positive gap for readers.
std::string DefaultGCodeFirmwareSession::begin_layer(const ConstPrintingLayerGroup &layer)
{
    if (!m_is_setup)
        throw std::logic_error("The firmware session was not initialized by begin_print().");
    const coord_t z_gap = layer.print_z() - m_layer_print_z;
    coord_t max_source_height = 0;
    if (layer.layer_count() > 0) {
        for (uint32_t layer_idx = 0; layer_idx < layer.layer_count(); ++layer_idx) {
            const Layer source_layer = layer.layer(layer_idx);
            if (!source_layer.valid() || source_layer.height() <= 0)
                throw std::invalid_argument("A source layer needs a positive height.");
            max_source_height = std::max(max_source_height, source_layer.height());
        }
    } else {
        max_source_height = z_gap;
    }
    std::string output = ";LAYER_CHANGE\n;Z:" +
        format_number(unscaled(layer.print_z())) + "\n;MAX_LAYER_HEIGHT:" +
        format_number(unscaled(max_source_height)) + "\n";

    m_layer_height = first_source_layer_height(layer).value_or(z_gap);
    ++m_layer_num;
    m_marker_height.reset();
    m_layer_print_z = layer.print_z();
    // A layer boundary is structural, not a machine movement. Explicit travel
    // geometry may first finish a wipe at the preceding Z and then apply a
    // ramped lift. When no such geometry exists, write_leaf_geometry() still
    // provides the legacy straight fallback to the first point at this Z.
    return output;
}

// Borrow attributes, validate dimensions and update marker caches while returning
// changed tags; fixed-E paths may omit both dimension tags when either is zero.
std::string DefaultGCodeFirmwareSession::write_printable_markers(
    const EPropertyAttributes &attributes, const bool fixed_e)
{
    const float width = attributes.c_extrusion_property_attributes::width;
    const float height = attributes.c_extrusion_property_attributes::height;
    if (!std::isfinite(width) || width < 0.f ||
        !std::isfinite(height) || height < 0.f ||
        (!fixed_e && (width == 0.f || height == 0.f)))
        throw std::invalid_argument(
            "A printable extrusion needs positive finite width and height attributes.");

    const std::string role_name =
        slic3r_api::extrusion_role_to_string(attributes.extrusion_role());
    const bool role_changed = !m_marker_role || *m_marker_role != role_name;
    const bool has_dimensions = width > 0.f && height > 0.f;
    const bool width_changed = has_dimensions && (!m_marker_width || *m_marker_width != width);
    const bool height_changed = has_dimensions && (!m_marker_height || *m_marker_height != height);

    std::string output;
    if (role_changed)
        output += ";TYPE:" + role_name + "\n";
    if (width_changed)
        output += ";WIDTH:" + format_number(width) + "\n";
    if (height_changed)
        output += ";HEIGHT:" + format_number(height) + "\n";

    if (role_changed)
        m_marker_role = role_name;
    if (width_changed)
        m_marker_width = width;
    if (height_changed)
        m_marker_height = height;
    return output;
}

std::string DefaultGCodeFirmwareSession::write_seam_marker(const ExtrusionEntity &loop) const {
    // like is_loop, but also work on loop broken by seam_gap
    const EPropertyPerimeter *loop_property = loop.get(EPropertyPerimeter::key);
    if (!loop_property)
        return {};

    // only write seam maker before first point of an external perimeter
    if (loop_property->shell_count() != 0)
        return {};

    // get seam point: we pick the first of the extrusion
    const c_vec3d serialized_start = m_formatter->quantize(machine_position(loop.front(), 0));

    const uint16_t precision = m_formatter->m_gcode_precision_xyz;
    return ";SEAM:" + format_number(serialized_start.x, precision) + ":" +
        format_number(serialized_start.y, precision) + "\n";
}

// Borrow a valid tool group, select its tool and return the owned selection
// string; a source height replaces script height only when an ordered extrusion
// has one. Uninitialized state, an invalid tool or encoder failure propagates;
// selection failure follows the height update, and the borrowed group is not
// retained.
std::string DefaultGCodeFirmwareSession::begin_tool_group(const ConstPrintingToolGroup &tool_group)
{
    if (!m_is_setup)
        throw std::logic_error("The firmware session was not initialized by begin_print().");
    const std::optional<coord_t> source_height = first_source_layer_height(tool_group);
    if (source_height)
        m_layer_height = *source_height;
    const bool custom_toolchange = has_toolchange_script(tool_group.events().before());
    const bool ordered_toolchange = tool_group_has_semantic_toolchange(tool_group);
    const std::string output = ordered_toolchange ? std::string() :
        select_extruder(tool_group.extruder_id(), !custom_toolchange);
    return output;
}

// Borrow a valid extrusion with a root, return an owned string of object-boundary
// and tree output, and set script height to its source layer before visiting tree
// events. An invalid session or missing root throws; later transition or visitor
// failures propagate after the height update. No plan data is owned, and a
// source-free extrusion leaves the prior height unchanged.
std::string DefaultGCodeFirmwareSession::write_extrusion(const ConstPrintingExtrusion &extrusion)
{
    if (!m_is_setup)
        throw std::logic_error("The firmware session was not initialized by begin_print().");
    const extrusion_entity_handle *root_handle = printing_extrusion_get_root(extrusion.handle());
    if (root_handle == nullptr)
        throw std::invalid_argument("The PrintingExtrusion has no extrusion root.");

    const std::optional<coord_t> source_height = source_layer_height(extrusion);
    if (source_height)
        m_layer_height = *source_height;
    const uint32_t object_id = extrusion.printing_catalog_id();
    // UINT32_MAX is deliberate for print-level auxiliary work and for any
    // extrusion that is outside a physical object-instance boundary.
    std::string output = transition_object(object_id);
    return output + write_extrusion_tree(ExtrusionEntity(root_handle), object_id);
}

std::string DefaultGCodeFirmwareSession::write_event(const ExtrusionEntity &event_root)
{
    if (!m_is_setup)
        throw std::logic_error("The firmware session was not initialized by begin_print().");
    // The object boundary must be written, and its E reset applied, before the
    // event tree is serialized; C++ does not order the operands of `+`.
    std::string output = transition_object(uint32_t(-1));
    return output + write_extrusion_tree(event_root);
}

// Borrow one root and remember its object only for this traversal. Return owned
// visitor output, clearing reopening state on both success and failure; event
// trees use the outside sentinel and can never request a labelled reopening.
std::string DefaultGCodeFirmwareSession::write_extrusion_tree(const ExtrusionEntity &root,
                                                            const uint32_t object_id)
{
    // Scope events and printable roots share property inheritance and event
    // handling. A fresh visitor isolates that lexical state while the session
    // retains machine state across both kinds of tree.
    m_extrusion_tree_object_id = object_id;
    m_object_block_reopen_pending = false;
    ExtrusionWriterVisitor visitor(*this);
    try {
        std::string output = visitor.write(root);
        m_extrusion_tree_object_id = uint32_t(-1);
        m_object_block_reopen_pending = false;
        return output;
    } catch (...) {
        m_extrusion_tree_object_id = uint32_t(-1);
        m_object_block_reopen_pending = false;
        throw;
    }
}

