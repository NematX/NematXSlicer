// Close the previously selected tool's axis interval and begin one at the selected tool's current used-filament value; callers invoke this immediately after every m_current_extruder_idx change outside setup so m_usage_tool follows, and SEMM state copying does not alter the departing tool's axis; this mutates only session counters, and invalid tool ownership propagates from extruder().
void DefaultGCodeFirmwareSession::settle_filament_usage()
{
    if (m_usage_tool)
        m_filament_used_mm.at(*m_usage_tool) +=
            extruder(*m_usage_tool).extrusion_axis().used_filament() - m_usage_start_mm;
    m_usage_tool = m_current_extruder_idx;
    m_usage_start_mm = m_usage_tool ?
        extruder(*m_usage_tool).extrusion_axis().used_filament() : 0.0;
}

// Copy closed per-tool usage and add the currently selected tool's open axis interval; return values own no session state, and inconsistent tool indices propagate as range failures.
std::vector<double> DefaultGCodeFirmwareSession::filament_used_mm() const
{
    std::vector<double> used = m_filament_used_mm;
    if (m_usage_tool)
        used.at(*m_usage_tool) +=
            extruder(*m_usage_tool).extrusion_axis().used_filament() - m_usage_start_mm;
    return used;
}

// Resolve a configured tool, optionally emit its selection, transfer shared SEMM
// state and settle its filament interval. An opt-in in-tree block closure requests
// reopening before the next geometry. Invalid IDs or encoders throw; absolute-E
// output resets only E coordinates, and selecting the current tool writes nothing.
std::string DefaultGCodeFirmwareSession::select_extruder(extruder_index_t tool_id, bool emit_command)
{
    DefaultExtruder &selected = extruder(tool_id);
    if (m_current_extruder_idx && *m_current_extruder_idx == tool_id)
        return {};

    DefaultExtruder *previous = m_current_extruder_idx ?
        &extruder(*m_current_extruder_idx) : nullptr;

    // A labelled block belongs to the tool that is still selected. A dialect that
    // opts in (closes_object_block_before_tool_change), or any block opened with a
    // retraction depth, is closed (exit retraction, end label, axis reset) before the
    // selection is written or recorded: the tool change is then never inside a block
    // a printer may skip, and no retraction runs on, or is accounted to, another tool.
    const std::string closed_block =
        m_object_block_open && (m_object_block_depth || closes_object_block_before_tool_change()) ?
        transition_object(uint32_t(-1)) : std::string();
    if (!closed_block.empty() && closes_object_block_before_tool_change() &&
        m_extrusion_tree_object_id != uint32_t(-1))
        m_object_block_reopen_pending = true;

    // Generate the tool command before committing the selected index. A
    // derived encoder may throw without leaving the session on a fictive tool.
    std::string output = emit_command ? encode_tool_change(selected.id()) : std::string();
    const bool reset_e = !output.empty() && !m_e_relative_mode;
    if (reset_e)
        output += encode_extrusion_axis_reset();
    if (m_single_extruder_multi_material && previous != nullptr) {
        selected.synchronize_runtime_from(*previous);
        // Native G10/G11 has one binary physical state in addition to the E
        // counters, so selecting another filament cannot start a second G10.
        m_native_retraction_active.at(tool_id) =
            m_native_retraction_active.at(*m_current_extruder_idx);
    }
    synchronize_selected_extruder_state(previous, selected);
    if (reset_e) {
        // Reset after SEMM state transfer so the copied coordinate cannot
        // replace the zero just emitted. Retraction and restart extras survive.
        selected.extrusion_axis().reset_E();
        m_e_position_known = true;
    }
    m_current_extruder_idx = tool_id;
    settle_filament_usage();
    return closed_block + output;
}

std::string DefaultGCodeFirmwareSession::move_to_group_start(const ConstPrintingGroup &group)
{
    // The caller has already established that this is a transition between
    // real object groups. A missing tool or position still makes the first
    // regular path responsible for establishing the machine position.
    if (!m_current_extruder_idx || !m_gantry.position())
        return {};
    for (uint32_t layer_idx = 0; layer_idx < group.layer_group_count(); ++layer_idx) {
        const ConstPrintingLayerGroup layer = group.layer_group(layer_idx);
        for (uint32_t tool_idx = 0; tool_idx < layer.tool_group_count(); ++tool_idx) {
            const ConstPrintingToolGroup tool_group = layer.tool_group(tool_idx);
            for (uint32_t extrusion_idx = 0; extrusion_idx < tool_group.extrusion_count(); ++extrusion_idx) {
                const ExtrusionEntity root = tool_group.extrusion(extrusion_idx).root();
                if (root.empty())
                    continue;
                const c_point first_point = root.front();
                const c_vec3d destination = {
                    unscaled(first_point.x) - current_extruder().xy_offset().x,
                    unscaled(first_point.y) - current_extruder().xy_offset().y,
                    m_gantry.position()->z
                };
                const std::optional<double> inherited_speed = m_gantry.requested_speed();
                m_gantry.request_speed(m_gantry.travel_speed());
                PreparedMove move;
                move.kind = PreparedMove::Kind::Travel;
                move.destination = destination;
                const std::string output = transition_wipe_marker(false) + write_lines(move);
                m_gantry.request_speed(inherited_speed);
                return output;
            }
        }
    }
    return {};
}

std::string DefaultGCodeFirmwareSession::write_requested_fan()
{
    if (!m_current_extruder_idx)
        throw std::invalid_argument("A fan request has no active tool.");
    DefaultExtruder &tool = current_extruder();
    if (!tool.fan().needs_encoding())
        return {};
    const std::string output = encode_fan(tool.id(), tool.fan().effective_speed_percent());
    tool.fan().mark_encoded();
    return output;
}

std::string DefaultGCodeFirmwareSession::transition_wipe_marker(const bool wipe)
{
    if (wipe == m_wipe_tag_open)
        return {};

    const std::string output = wipe ? ";WIPE_START\n" : ";WIPE_END\n";
    m_wipe_tag_open = wipe;
    return output;
}

// Copy inherited speed, fan and pressure-advance requests into the current machine state; the input is borrowed, no G-code is emitted, and heater targets remain unchanged until an entry event or external G-code.
void DefaultGCodeFirmwareSession::apply_requested_state(const RequestedState &state)
{
    m_gantry.request_speed(state.speed_mm_per_s ?
        std::optional<double>(*state.speed_mm_per_s) : std::optional<double>());

    if (!m_current_extruder_idx)
        return;

    // Fan and pressure-advance properties are requested on the currently
    // selected physical tool; heater targets are changed only by entry events
    // or external G-code and therefore are not part of lexical state.
    DefaultExtruder &tool = current_extruder();
    tool.fan().request_speed_percent(state.fan.is_set() ?
        std::optional<double>(state.fan.percent) : std::optional<double>());
    tool.pressure_advance().request(state.pressure_advance ?
        std::optional<double>(*state.pressure_advance) : std::optional<double>());
}

c_vec3d DefaultGCodeFirmwareSession::machine_position(c_point point, coord_t z_offset) const
{
    const DefaultExtruder &tool = current_extruder();
    const c_vec2d tool_offset = tool.xy_offset();
    return {
        unscaled(point.x) - tool_offset.x,
        unscaled(point.y) - tool_offset.y,
        unscaled(m_layer_print_z + z_offset) + m_gantry.z_offset() - tool.z_offset()
    };
}

double DefaultGCodeFirmwareSession::segment_length_mm(const c_extrusion_segment &segment) const
{
    const double chord = c_point_distance_to(segment.point_a, segment.point_b);
    if (segment.radius == 0.f)
        return unscaled(chord);

    const double radius = std::abs(double(segment.radius));
    if (radius <= 0.0 || chord > radius * 2.0 + double(SCALED_EPSILON))
        throw std::invalid_argument("An extrusion arc has an invalid radius.");

    // A positive radius denotes the shorter circular arc. A negative radius
    // denotes the complementary long arc between the same endpoints.
    const double ratio = std::clamp(chord / (2.0 * radius), 0.0, 1.0);
    double angle = 2.0 * std::asin(ratio);
    if (segment.radius < 0.f)
        angle = 2.0 * PI - angle;
    return unscaled(radius * angle);
}

std::string DefaultGCodeFirmwareSession::write_native_retract(const double target)
{
    DefaultExtruder &tool = current_extruder();
    const bool changed = tool.extrusion_axis().retract_with_firmware(target);
    uint8_t &active = m_native_retraction_active.at(*m_current_extruder_idx);
    if (!changed || active != 0)
        return {};
    active = 1;
    return encode_firmware_retraction(true);
}

std::string DefaultGCodeFirmwareSession::write_native_unretract()
{
    DefaultExtruder &tool = current_extruder();
    if (!tool.extrusion_axis().unretract_with_firmware())
        return {};
    m_native_retraction_active.at(*m_current_extruder_idx) = 0;
    return encode_firmware_retraction(false);
}

// Retract the active tool down to `target` mm and return the text. An explicit E
// move uses the tool's retract speed; native retraction writes the dialect command
// once while the tool stays retracted. Nothing is written when the tool is already
// at least that deep. The inherited speed request is restored. Requires a tool.
std::string DefaultGCodeFirmwareSession::write_retraction(const double target)
{
    DefaultExtruder &tool = current_extruder();
    if (tool.extrusion_axis().retract_to_go(target) <= EPSILON)
        return {};

    const std::optional<double> inherited_speed = m_gantry.requested_speed();
    std::string output;
    if (m_use_firmware_retraction) {
        const std::string command = write_native_retract(target);
        if (!command.empty())
            output += transition_wipe_marker(false) + command;
    } else {
        if (tool.extrusion_axis().retract_speed() > 0.0)
            m_gantry.request_speed(tool.extrusion_axis().retract_speed());
        PreparedMove move;
        move.kind = PreparedMove::Kind::Extrusion;
        move.extrusion = tool.extrusion_axis().retract(target);
        output += transition_wipe_marker(false);
        output += write_lines(move);
    }
    m_gantry.request_speed(inherited_speed);
    return output;
}

// Wrap `gcode` in a retraction/unretraction pair of the active tool.
// Contract: `gcode` is appended as is and never interpreted, so it must not change the
// tool, the E position or the E mode; `retract_length` is finite and >= 0 (0 or less
// writes `gcode` alone). The caller closes any open object block first when the text
// must not be skipped with an object. Requires a selected tool.
// Effects on the E state:
//   - tool not retracted: the pair is temporary. Only the retraction created here is
//     repaid, so the tool ends with no retraction, and the restart extras scheduled
//     before the call stay scheduled for the next real unretraction (the unretraction
//     below would otherwise deposit them during the pause and clear them);
//   - tool already retracted, even partially: only the complement up to `retract_length`
//     is written (write_block_retraction()), the existing debt is left for the following
//     extrusion;
//   - firmware retraction already active (G10 sent): the firmware keeps its own depth,
//     nothing is added, so the logical state keeps matching the printer's.
std::string DefaultGCodeFirmwareSession::write_with_retraction(const std::string &gcode,
                                                               const double retract_length)
{
    if (!(retract_length > 0.0))
        return gcode;
    ExtrusionAxisState &axis = current_extruder().extrusion_axis();
    const bool was_retracted = axis.retracted() > EPSILON;
    std::string output = write_block_retraction(retract_length);
    output += gcode;
    if (was_retracted)
        return output;

    // Repay the temporary retraction alone: park the extras, unretract, schedule them back.
    // If the unretraction throws the extras are not restored; that is intended: the
    // exception aborts the whole export and the session is dropped (every export creates
    // a new session, see run_impl in BuiltinGCodeFirmwares.cpp), so no state is reused.
    const double restart_extra = axis.restart_extra();
    const double restart_extra_toolchange = axis.restart_extra_toolchange();
    axis.schedule_restart_extra(0.0, false);
    axis.schedule_restart_extra(0.0, true);
    output += write_full_unretraction();
    axis.schedule_restart_extra(restart_extra, false);
    axis.schedule_restart_extra(restart_extra_toolchange, true);
    return output;
}

// Retract the active tool for a labelled block down to `depth` mm. With native
// retraction already active the firmware's own depth is kept: no logical complement
// is recorded. Otherwise it is write_retraction().
std::string DefaultGCodeFirmwareSession::write_block_retraction(const double depth)
{
    if (m_use_firmware_retraction && m_native_retraction_active.at(*m_current_extruder_idx) != 0)
        return {};
    return write_retraction(depth);
}

// Repay the whole retraction of the active tool and return the text: an explicit E
// move at the deretract speed (restart extras included, as for any unretraction),
// or the native unretract command. Nothing is written when the tool is not
// retracted. The inherited speed request is restored. Requires a tool.
std::string DefaultGCodeFirmwareSession::write_full_unretraction()
{
    DefaultExtruder &tool = current_extruder();
    if (tool.extrusion_axis().retracted() <= EPSILON)
        return {};

    const std::optional<double> inherited_speed = m_gantry.requested_speed();
    std::string output;
    if (m_use_firmware_retraction) {
        const std::string command = write_native_unretract();
        if (!command.empty())
            output += transition_wipe_marker(false) + command;
    } else {
        if (tool.extrusion_axis().deretract_speed() > 0.0)
            m_gantry.request_speed(tool.extrusion_axis().deretract_speed());
        PreparedMove move;
        move.kind = PreparedMove::Kind::Extrusion;
        move.extrusion = std::optional<double>(tool.extrusion_axis().unretract());
        output += transition_wipe_marker(false);
        output += write_lines(move);
    }
    m_gantry.request_speed(inherited_speed);
    return output;
}

// Borrow a leaf and inherited requests, validate its process and planar lengths,
// then return movement text and advance machine/E state; fixed filament deltas
// bypass flow conversion and use a copied axis until all segment lines succeed,
// and they leave the retraction state untouched because they are raw filament
// moves.
std::string DefaultGCodeFirmwareSession::write_leaf_geometry(const ExtrusionEntity &leaf,
                                                              const RequestedState &state)
{
    if (!m_current_extruder_idx)
        throw std::invalid_argument("An extrusion movement has no active tool.");
    if (!state.attributes)
        throw std::invalid_argument("An extrusion movement needs effective attributes.");
    const bool is_travel = RAW_EXTRUSION_ROLE_IS_TRAVEL(state.attributes->extrusion_role());
    const bool is_wipe = RAW_EXTRUSION_ROLE_IS_WIPE(state.attributes->extrusion_role());
    const bool is_retract = RAW_EXTRUSION_ROLE_IS_RETRACT(state.attributes->extrusion_role());
    const bool is_unretract = RAW_EXTRUSION_ROLE_IS_UNRETRACT(state.attributes->extrusion_role());
    const EPropertyExtrusionAxis *axis = leaf.get(EPropertyExtrusionAxis::key);
    const EPropertySpecialCommand *command = leaf.get(EPropertySpecialCommand::key);
    const bool fixed_e = command != nullptr && command->code == C_EXTRUSION_SPECIAL_COMMAND_EXTRUSION;
    if (fixed_e && axis != nullptr)
        throw std::invalid_argument("A leaf cannot combine EXTRUSION and an extrusion-axis request.");
    if (fixed_e && !std::isfinite(command->extra_data))
        throw std::invalid_argument("A geometric EXTRUSION request needs a finite filament delta.");
    if (is_wipe && !is_travel)
        throw std::invalid_argument("A wipe movement must also carry the Travel role.");
    if (axis != nullptr && !is_wipe)
        throw std::invalid_argument("A geometric extrusion-axis request is only valid on a Wipe leaf.");
    if (is_retract && is_unretract)
        throw std::invalid_argument("A Wipe leaf cannot retract and unretract at the same time.");
    if ((is_retract || is_unretract) && axis == nullptr)
        throw std::invalid_argument("A semantic Wipe role needs an extrusion-axis request.");
    if (axis != nullptr &&
        ((is_retract && axis->operation != C_EXTRUSION_AXIS_OPERATION_RETRACT_TO) ||
         (is_unretract && axis->operation != C_EXTRUSION_AXIS_OPERATION_UNRETRACT) ||
         (!is_retract && !is_unretract)))
        throw std::invalid_argument("A geometric extrusion-axis operation does not match its Wipe role.");
    if (axis != nullptr &&
        ((axis->operation == C_EXTRUSION_AXIS_OPERATION_RETRACT_TO &&
          (!std::isfinite(axis->value) || axis->value < 0.0)) ||
         (axis->operation == C_EXTRUSION_AXIS_OPERATION_UNRETRACT &&
          !std::isfinite(axis->restart_extra))))
        throw std::invalid_argument("A geometric extrusion-axis request contains an invalid value.");
    if (!is_travel && !fixed_e &&
        (state.attributes->c_extrusion_property_attributes::mm3_per_mm <= 0.0 ||
         !std::isfinite(state.attributes->c_extrusion_property_attributes::mm3_per_mm)))
        throw std::invalid_argument("A printable extrusion needs valid flow attributes.");
    if (!state.speed_mm_per_s || !std::isfinite(*state.speed_mm_per_s) ||
        *state.speed_mm_per_s <= 0.f)
        throw std::invalid_argument("An extrusion movement needs a finite positive speed.");
    const std::optional<uint32_t> acceleration =
        validated_acceleration_request(state.acceleration_mm_per_s2);

    // A present property updates the logical register selected by the leaf
    // role. An absent property deliberately preserves both existing requests,
    // matching the zero-disabled acceleration settings used by the slicer.
    if (acceleration) {
        if (is_travel)
            m_gantry.request_travel_acceleration(acceleration);
        else
            m_gantry.request_print_acceleration(acceleration);
    }
    apply_requested_state(state);
    std::string output = is_wipe ? std::string() : transition_wipe_marker(false);
    if (is_printable_role(state.attributes->extrusion_role()))
        output += write_printable_markers(*state.attributes, fixed_e);
    const c_extrusion_segment first_segment = leaf.segment(0);
    output += approach_leaf_point(first_segment.point_a, state.z_offset + first_segment.z_offset_a);

    // The first deposited geometry of a block opened with a retraction depth is
    // preceded by an explicit unretraction when a debt remains, so the extrusion
    // is complete. A plan that already repaid the debt (unretract event after the
    // travel) leaves nothing to write.
    if (m_object_block_unretract_pending && !is_travel) {
        m_object_block_unretract_pending = false;
        output += write_full_unretraction();
    }

    if (is_wipe)
        output += transition_wipe_marker(true);

    // A semantic geometric request is resolved from the live E state once for
    // the complete leaf. The axis state returns one already-quantized value per
    // planar segment, so firmware syntax never has to reproduce E arithmetic.
    std::vector<std::optional<double>> semantic_e_values;
    std::optional<ExtrusionAxisState> planned_axis;
    bool native_unretract_pending = false;
    if (axis != nullptr || fixed_e) {
        std::vector<double> segment_lengths;
        segment_lengths.reserve(leaf.segment_count());
        double total_segment_length = 0.0;
        for (uint32_t segment_idx = 0; segment_idx < leaf.segment_count(); ++segment_idx) {
            const double length = segment_length_mm(leaf.segment(segment_idx));
            segment_lengths.push_back(length);
            total_segment_length += length;
        }
        if (!std::isfinite(total_segment_length) || total_segment_length <= EPSILON)
            throw std::invalid_argument(
                "A geometric extrusion-axis request needs a positive planar length.");

        DefaultExtruder &tool = current_extruder();
        if (fixed_e) {
            // The final positive segment takes the subtraction remainder so
            // all signed filament deltas sum to the requested amount exactly.
            planned_axis = tool.extrusion_axis();
            semantic_e_values.resize(segment_lengths.size());
            size_t last_positive_idx = segment_lengths.size() - 1;
            while (segment_lengths[last_positive_idx] == 0.0)
                --last_positive_idx;
            double distributed_amount = 0.0;
            for (size_t idx = 0; idx < segment_lengths.size(); ++idx) {
                if (segment_lengths[idx] == 0.0)
                    continue;
                const double amount = idx == last_positive_idx ?
                    command->extra_data - distributed_amount :
                    command->extra_data * segment_lengths[idx] / total_segment_length;
                semantic_e_values[idx] = planned_axis->extrude(amount);
                distributed_amount += amount;
            }
        } else if (m_use_firmware_retraction) {
            if (is_retract) {
                output += write_native_retract(axis->value);
            } else {
                tool.extrusion_axis().schedule_restart_extra(
                    axis->restart_extra, axis->toolchange != 0);
                native_unretract_pending = tool.extrusion_axis().need_unretract();
            }
        } else {
            planned_axis = tool.extrusion_axis();
            semantic_e_values = is_retract ?
                planned_axis->retract_along(axis->value, segment_lengths) :
                planned_axis->unretract_along(
                    axis->restart_extra, axis->toolchange != 0, segment_lengths);
        }
    }

    // Convert every geometric segment into one prepared machine move. A travel
    // uses the same resolved speed property but deliberately carries no E.
    // Printable paths compute E from true arc length and preserve the original
    // arc for G2/G3 output.
    for (uint32_t segment_idx = 0; segment_idx < leaf.segment_count(); ++segment_idx) {
        const c_extrusion_segment segment = leaf.segment(segment_idx);

        PreparedMove move;
        move.kind = is_wipe ? PreparedMove::Kind::Wipe :
            (is_travel ? PreparedMove::Kind::Travel : PreparedMove::Kind::Extrusion);
        move.destination = machine_position(segment.point_b, state.z_offset + segment.z_offset_b);
        if (fixed_e || (axis != nullptr && !m_use_firmware_retraction)) {
            move.extrusion = semantic_e_values[segment_idx];
        } else if (!is_travel) {
            const double path_length = segment_length_mm(segment);
            const double delta_e = path_length * current_extruder().extrusion_axis().e_per_mm(
                state.attributes->c_extrusion_property_attributes::mm3_per_mm);
            // Printing extrusion is a raw move that repays any outstanding
            // retraction before depositing filament.
            move.extrusion = current_extruder().extrusion_axis().extrude(delta_e);
            current_extruder().extrusion_axis().repay_retraction(delta_e);
        }
        move.radius_mm = segment.radius == 0.f ? 0.f : float(unscaled(double(segment.radius)));
        move.arc_orientation = segment.orientation;
        output += write_lines(move);
    }

    // Commit explicit-E accounting only after every movement line has been
    // generated. Native unretraction is intentionally delayed until the end of
    // the approach, while native retraction was required before its wipe path.
    if (planned_axis)
        current_extruder().extrusion_axis() = *planned_axis;
    if (native_unretract_pending) {
        const std::string command = write_native_unretract();
        if (!command.empty())
            output += transition_wipe_marker(false) + command;
    }
    return output;
}

// Convert a scaled point and Z offset to machine coordinates and return approach
// commands only when the quantized position differs; owned gantry state advances,
// the inherited speed is restored, and encoding failures propagate to the caller.
// The first approach raises vertically to lift_min before moving XY, then descends
// at the destination. An unknown start position uses a Z-only absolute-mm move.
// Both the floor and ceiling are transformed from print Z to machine Z using the
// same gantry and tool corrections as the requested path position.
std::string DefaultGCodeFirmwareSession::approach_leaf_point(c_point point, coord_t z_offset)
{
    const c_vec3d position = machine_position(point, z_offset);
    const c_vec3d quantized = m_formatter->quantize(position);
    const bool first = m_first_approach;
    m_first_approach = false;
    if ((!first || m_lift_min <= 0.0) && m_gantry.position() && !coordinates_differ(*m_gantry.position(), quantized))
        return {};
    const std::optional<double> print_speed = m_gantry.requested_speed();
    m_gantry.request_speed(m_gantry.travel_speed());
    PreparedMove travel;
    travel.kind = PreparedMove::Kind::Travel;
    std::string output = transition_wipe_marker(false);
    if (first && m_lift_min > 0.0) {
        const double frame_offset = m_gantry.z_offset() - current_extruder().z_offset();
        double floor = std::max({m_lift_min + frame_offset, position.z, m_gantry.position() ? m_gantry.position()->z : position.z});
        if (m_max_print_height > 0.0) floor = std::min(floor, m_max_print_height + frame_offset);
        if (m_gantry.position()) {
            travel.destination = *m_gantry.position();
            travel.destination->z = floor;
            output += write_lines(travel);
        } else {
            // No XY is known yet, so establish only Z before the first approach.
            if (!m_units_in_mm) { output += "G21\n"; m_units_in_mm = true; }
            if (m_xyz_relative_mode) { output += "G90\n"; m_xyz_relative_mode = false; }
            output += "G1 Z" + format_number(floor, m_formatter->m_gcode_precision_xyz) +
                " F" + format_number(m_gantry.travel_speed() * 60.0) + "\n";
        }
        travel.destination = position;
        travel.destination->z = floor;
        output += write_lines(travel);
    }
    travel.destination = position;
    output += write_lines(travel);
    m_gantry.request_speed(print_speed);
    return output;
}

// Borrow a one-point volume leaf and inherited process requests; validate positive
// finite volume, flow, dimensions and speed with an active tool, then return markers,
// travel and E-only output. The session advances E and repays debt without inventing
// unretraction, except the one that a block opened with a retraction depth still owes before
// its first material; filament speed includes the multiplier in both E modes. Invalid
// requests or encoding failures throw, and the temporary speed is restored on success.
// Support deposits trial a copied E state: a swallowed half-step request advances
// by one displayed step and clears the remainder; smaller invisible requests dwell.
std::string DefaultGCodeFirmwareSession::write_deposit(
    const ExtrusionEntity &leaf, const RequestedState &state)
{
    if (!m_current_extruder_idx || !state.attributes || !state.speed_mm_per_s)
        throw std::invalid_argument("DEPOSIT needs an active tool, attributes and speed.");
    const EPropertySpecialCommand *command = leaf.get(EPropertySpecialCommand::key);
    const c_extrusion_property_attributes &attributes = *state.attributes;
    if (leaf.point_count() != 1 || leaf.child_count() != 0 || state.extrusion_axis ||
        !std::isfinite(command->extra_data) || command->extra_data <= 0.0 ||
        !is_printable_role(state.attributes->extrusion_role()) ||
        !std::isfinite(attributes.mm3_per_mm) || attributes.mm3_per_mm <= 0.0 ||
        !std::isfinite(attributes.width) || attributes.width <= 0.f ||
        !std::isfinite(attributes.height) || attributes.height <= 0.f ||
        !std::isfinite(*state.speed_mm_per_s) || *state.speed_mm_per_s <= 0.f)
        throw std::invalid_argument("DEPOSIT needs positive finite volume and printable process attributes.");
    ExtrusionAxisState &axis = current_extruder().extrusion_axis();
    const double filament_speed = *state.speed_mm_per_s * attributes.mm3_per_mm * axis.filament_per_mm3();
    const std::optional<uint32_t> acceleration = validated_acceleration_request(state.acceleration_mm_per_s2);
    if (acceleration)
        m_gantry.request_print_acceleration(acceleration);
    apply_requested_state(state);
    std::string output = transition_wipe_marker(false) + write_printable_markers(*state.attributes);
    output += approach_leaf_point(leaf.point(0), state.z_offset + leaf.z_offset(0));
    // The first material of a block opened with a retraction depth is preceded by an explicit
    // unretraction, as for a geometric leaf; otherwise the deposit would only repay the debt
    // and lay nothing. This runs before the trial copy of the E state below.
    if (m_object_block_unretract_pending) {
        m_object_block_unretract_pending = false;
        output += write_full_unretraction();
    }
    const std::optional<double> inherited_speed = m_gantry.requested_speed();
    m_gantry.request_speed(filament_speed);
    const double delta_e = command->extra_data * axis.e_per_mm3();
    PreparedMove move;
    move.kind = PreparedMove::Kind::Extrusion;
    const bool support = RAW_EXTRUSION_ROLE_IS_SUPPORT(attributes.role);
    if (support) {
        // Trial quantization without changing the owned axis. A negative carried
        // remainder can hide a deposit large enough to request its own E word.
        const double step = GCodeFormatter::pow_10_inv[m_formatter->m_gcode_precision_e];
        ExtrusionAxisState planned_axis = axis;
        move.extrusion = planned_axis.extrude(delta_e);
        if (!move.extrusion && delta_e >= SUPPORT_DEPOSIT_MIN_STEP_FRACTION * step) {
            const double forced_delta = step - axis.extruded_dE_left();
            planned_axis = axis;
            move.extrusion = planned_axis.extrude(forced_delta);
            planned_axis.repay_retraction(step);
        } else {
            planned_axis.repay_retraction(delta_e);
        }
        axis = planned_axis;
    } else {
        move.extrusion = axis.extrude(delta_e);
        axis.repay_retraction(delta_e);
    }
    output += write_lines(move);
    // Invisible sub-step support volume stays in the axis remainder. The dwell
    // occurs after approach travel and is not counted by the estimator or reader.
    if (support && !move.extrusion)
        output += encode_pause(SUPPORT_DEPOSIT_PAUSE_MS);
    m_gantry.request_speed(inherited_speed);
    return output;
}

// Borrow an E-only request and return commands while updating the active tool;
// invalid roles/values throw. Positive UNRETRACT limits restore only outstanding
// filament, retain extras, and do nothing under native G10/G11 retraction.
std::string DefaultGCodeFirmwareSession::write_extrusion_axis_event(
    const EPropertyExtrusionAxis &axis,
    const RequestedState &state)
{
    if (!m_current_extruder_idx)
        throw std::invalid_argument("An extrusion-axis event has no active tool.");

    std::string output;
    apply_requested_state(state);
    DefaultExtruder &tool = current_extruder();
    const std::optional<double> inherited_speed = m_gantry.requested_speed();
    const std::optional<uint32_t> acceleration =
        validated_acceleration_request(state.acceleration_mm_per_s2);
    if (acceleration)
        m_gantry.request_print_acceleration(acceleration);

    const raw_extrusion_role role = state.attributes ? state.attributes->extrusion_role() : 0;
    if (RAW_EXTRUSION_ROLE_IS_RETRACT(role)) {
        if (axis.operation != C_EXTRUSION_AXIS_OPERATION_RETRACT_TO ||
            !std::isfinite(axis.value) || axis.value < 0.0)
            throw std::invalid_argument("A Retract event needs a valid retract-to request.");
        //note: i don't need to check the retraction role, as it shoudl be the same as the previous extrusion.
        output += write_retraction(axis.value);
    } else if (RAW_EXTRUSION_ROLE_IS_UNRETRACT(role)) {
        if (axis.operation != C_EXTRUSION_AXIS_OPERATION_UNRETRACT ||
            !std::isfinite(axis.value) || axis.value < 0.0 || !std::isfinite(axis.restart_extra))
            throw std::invalid_argument("An Unretract event needs a valid unretract request.");
        const bool partial = axis.value > 0.0;
        if (!partial)
            tool.extrusion_axis().schedule_restart_extra(axis.restart_extra, axis.toolchange != 0);
        if ((partial && (m_use_firmware_retraction || tool.extrusion_axis().retracted() == 0.0)) ||
            (!partial && !tool.extrusion_axis().need_unretract())) {
            m_gantry.request_speed(inherited_speed);
            return output;
        }
        if (m_use_firmware_retraction) {
            const std::string command = write_native_unretract();
            if (!command.empty())
                output += transition_wipe_marker(false) + command;
        } else {
            if (tool.extrusion_axis().deretract_speed() > 0.0)
                m_gantry.request_speed(tool.extrusion_axis().deretract_speed());
            PreparedMove move;
            move.kind = PreparedMove::Kind::Extrusion;
            if (partial) {
                // A partial unretract restores at most the outstanding retraction.
                const double amount = std::min(
                    axis.value, tool.extrusion_axis().retracted());
                move.extrusion = tool.extrusion_axis().extrude(amount);
                tool.extrusion_axis().repay_retraction(amount);
            } else {
                move.extrusion = std::optional<double>(tool.extrusion_axis().unretract());
            }
            const raw_extrusion_role next_role = role & ~RAW_EXTRUSION_ROLE_UNRETRACT;
            output += transition_wipe_marker(false);
            if (next_role != RAW_EXTRUSION_ROLE_NONE && is_printable_role(next_role)) {
                const std::string role_name = slic3r_api::extrusion_role_to_string(next_role);
                const bool role_changed = !m_marker_role || *m_marker_role != role_name;
                if (role_changed)
                    output += ";TYPE:" + role_name + "\n";
                if (role_changed)
                    m_marker_role = role_name;
            }
            output += write_lines(move);
        }
    } else {
        throw std::invalid_argument(
            "An E-only extrusion-axis event needs a Retract or Unretract role.");
    }

    m_gantry.request_speed(inherited_speed);
    return output;
}

// Validate one persistent heater entry event, update the addressed heater's requested target and emit its immediate command when the requested encoding has changed; negative targets, missing active tools, invalid tool ids, SEMM cross-tool requests and unknown heater kinds throw without taking ownership.
std::string DefaultGCodeFirmwareSession::write_heater_event(const EPropertyHeater &heater)
{
    if (heater.temperature_C < 0)
        throw std::invalid_argument("A heater event has a negative temperature.");

    HeaterState *target_state = nullptr;
    extruder_index_t tool_id = EXTRUDER_ID_UNKNOWN;
    if (heater.heater == C_EXTRUSION_HEATER_TOOL) {
        tool_id = heater.tool;
        if (tool_id == EXTRUDER_ID_UNKNOWN) {
            if (!m_current_extruder_idx)
                throw std::invalid_argument("A heater event for the active tool has no active tool.");
            tool_id = *m_current_extruder_idx;
        }
        DefaultExtruder &tool = extruder(tool_id);
        if (single_extruder_multi_material() &&
            (!m_current_extruder_idx || tool_id != *m_current_extruder_idx))
            throw std::invalid_argument("A SEMM heater event cannot address a non-active tool.");
        target_state = &tool.heater();
    } else if (heater.heater == C_EXTRUSION_HEATER_BED) {
        target_state = &m_printer.bed_heater();
    } else if (heater.heater == C_EXTRUSION_HEATER_CHAMBER) {
        target_state = &m_printer.chamber_heater();
    } else {
        throw std::invalid_argument("A heater event contains an unknown heater kind.");
    }

    HeaterState &target = *target_state;
    target.request_temperature(heater.temperature_C);
    const bool wait = heater.wait != 0;
    if (wait ? !target.needs_wait_encoding() : !target.needs_encoding())
        return {};
    const int16_t effective_temperature = target.effective_temperature();
    std::string output;
    if (heater.heater == C_EXTRUSION_HEATER_TOOL)
        output = encode_tool_temperature(tool_id, effective_temperature, wait);
    else if (heater.heater == C_EXTRUSION_HEATER_BED)
        output = encode_bed_temperature(effective_temperature, wait);
    else
        output = encode_chamber_temperature(effective_temperature, wait);
    if (wait)
        target.mark_encoded_with_wait();
    else
        target.mark_encoded();
    return output;
}

// Borrow an entry command and inherited state, returning dialect output while
// updating owned machine state; malformed values and DEPOSIT outside a point leaf throw.
std::string DefaultGCodeFirmwareSession::write_special_command(
    const EPropertySpecialCommand &command,
    const RequestedState &state)
{
    apply_requested_state(state);
    switch (command.code) {
    case C_EXTRUSION_SPECIAL_COMMAND_DEPOSIT:
        throw std::invalid_argument("DEPOSIT is emitted only at a one-point leaf.");
    case C_EXTRUSION_SPECIAL_COMMAND_TOOLCHANGE: {
        if (!std::isfinite(command.extra_data) || command.extra_data < 0.0 ||
            command.extra_data > double(std::numeric_limits<extruder_index_t>::max()) ||
            std::trunc(command.extra_data) != command.extra_data)
            throw std::invalid_argument("A tool-change command contains an invalid tool id.");
        const extruder_index_t tool_id = static_cast<extruder_index_t>(command.extra_data);
        const std::string output = select_extruder(tool_id);
        apply_requested_state(state);
        return output;
    }
    case C_EXTRUSION_SPECIAL_COMMAND_SAVE_AND_RESET_SPEED_RATIO:
        return encode_save_speed_ratio(command.extra_data);
    case C_EXTRUSION_SPECIAL_COMMAND_RESTORE_SPEED_RATIO:
        return encode_restore_speed_ratio();
    case C_EXTRUSION_SPECIAL_COMMAND_FLUSH_PLANNER_QUEUE:
        return encode_flush_planner();
    case C_EXTRUSION_SPECIAL_COMMAND_EXTRUSION:
    case C_EXTRUSION_SPECIAL_COMMAND_RETRACT: {
        DefaultExtruder &tool = current_extruder();
        const std::optional<double> inherited_speed = m_gantry.requested_speed();
        const std::optional<uint32_t> acceleration =
            validated_acceleration_request(state.acceleration_mm_per_s2);
        if (acceleration)
            m_gantry.request_print_acceleration(acceleration);
        if (command.code == C_EXTRUSION_SPECIAL_COMMAND_RETRACT) {
            const double speed = command.extra_data < 0.0 ?
                tool.extrusion_axis().retract_speed() : tool.extrusion_axis().deretract_speed();
            if (speed > 0.0)
                m_gantry.request_speed(speed);
        }
        PreparedMove move;
        move.kind = PreparedMove::Kind::Extrusion;
        move.extrusion = tool.extrusion_axis().extrude(command.extra_data);
        // EXTRUSION is a raw filament move; the explicit RETRACT command keeps
        // its retract/deretract meaning.
        if (command.code == C_EXTRUSION_SPECIAL_COMMAND_RETRACT) {
            if (command.extra_data < 0.0)
                tool.extrusion_axis().add_retraction(-command.extra_data);
            else
                tool.extrusion_axis().repay_retraction(command.extra_data);
        }
        const std::string output = transition_wipe_marker(false) + write_lines(move);
        m_gantry.request_speed(inherited_speed);
        return output;
    }
    case C_EXTRUSION_SPECIAL_COMMAND_PAUSE:
        return encode_pause(command.extra_data);
    case C_EXTRUSION_SPECIAL_COMMAND_WAIT_FOR_TEMP: {
        DefaultExtruder &tool = current_extruder();
        if (!tool.heater().requested_temperature())
            throw std::invalid_argument("A temperature wait command has no requested tool temperature.");
        if (!tool.heater().needs_wait_encoding())
            return {};
        const std::string output = encode_tool_temperature(
            tool.id(), tool.heater().effective_temperature(), true);
        tool.heater().mark_encoded_with_wait();
        return output;
    }
    case C_EXTRUSION_SPECIAL_COMMAND_DISABLE_PREVIEW:
        m_printer.set_preview_enabled(false);
        return {};
    case C_EXTRUSION_SPECIAL_COMMAND_ENABLE_PREVIEW:
        m_printer.set_preview_enabled(true);
        return {};
    case C_EXTRUSION_SPECIAL_COMMAND_EXTRUDER_CURRENT:
        return encode_extruder_current(current_extruder().id(), command.extra_data);
    }
    throw std::invalid_argument("An extrusion tree contains an unknown special command.");
}

// Borrow stored script/text, process and reconcile its machine effects, then
// return emitted text. Toolchange scripts establish an absolute E origin before
// later E preparation; coordinate resets preserve debt/extras. Invalid script
// metadata, processing or Reader reconciliation throws without taking ownership.
std::string DefaultGCodeFirmwareSession::write_custom_gcode(
    const ExtrusionEntity &entity,
    const EPropertyCustomGcode &custom_gcode)
{
    const std::string text = entity.stored_string(custom_gcode.text_id);
    if (custom_gcode.kind == C_EXTRUSION_CUSTOM_GCODE_SCRIPT) {
        if (custom_gcode.script_type == GCODE_SCRIPT_TYPE_INVALID)
            throw std::invalid_argument("A custom G-code script has no script type.");

        const Config *producer_config = nullptr;
        if (custom_gcode.config_id != EXTRUSION_DATA_ID_INVALID) {
            if (!m_script_config)
                throw std::logic_error(
                    "The firmware session has no storage for a scripted G-code Config.");

            // The property owns a complete NUL-terminated SCFG snapshot. Rebuild
            // it in reusable plugin storage immediately before host preparation.
            uint32_t byte_size = 0;
            const char *serialized = static_cast<const char *>(
                entity.stored_data(custom_gcode.config_id, &byte_size));
            if (serialized == nullptr || byte_size == 0 || serialized[byte_size - 1] != '\0')
                throw std::invalid_argument("A custom G-code script has an invalid stored Config.");
            m_script_config->clear();
            m_script_config->deserialize_all(std::string(serialized, serialized + byte_size - 1));
            producer_config = &*m_script_config;
        }
        std::string output = process_script(
            custom_gcode.script_type, text, producer_config, custom_gcode.processing_extruder_id);
        if (!output.empty() && output.back() != '\n')
            output += '\n';
        const bool toolchange_script = custom_gcode.script_type == GCODE_SCRIPT_TYPE_TOOLCHANGE_GCODE;
        synchronize_after_custom_gcode(output);
        if (toolchange_script && m_current_extruder_idx) {
            if (!m_e_relative_mode) {
                // Always establish a zero E origin after the script, even if it already reset E.
                output += encode_extrusion_axis_reset();
                current_extruder().extrusion_axis().reset_E();
            }
            // Absolute output now has a zero origin. Relative output needs no
            // origin, so neither mode needs the unknown-E fallback on its next move.
            m_e_position_known = true;
        }
        return output;
    }
    if (custom_gcode.script_type != GCODE_SCRIPT_TYPE_INVALID ||
        custom_gcode.config_id != EXTRUSION_DATA_ID_INVALID ||
        custom_gcode.processing_extruder_id != EXTRUDER_ID_UNKNOWN)
        throw std::invalid_argument("Raw G-code and comments cannot carry script metadata.");
    const std::string output = encode_custom_gcode(custom_gcode.kind, text);
    synchronize_after_custom_gcode(output);
    return output;
}

// Replay borrowed text with the selected Reader, adopt only proven machine values, including requested and encoded heater targets, and settle the per-tool usage interval after any reported tool change.
// The retraction state is not adopted: the reader cannot prove it, and only the
// explicit retraction operations and script declarations change it.
// Unknown values invalidate caches; the Reader reports only final values, so an
// intermediate target changed and then restored by one script is not observable.
// Reader or state validation errors propagate.
void DefaultGCodeFirmwareSession::synchronize_after_custom_gcode(const std::string &text)
{
    // Generated G-code and custom G-code share one physical printer. Before
    // writing the next generated command, replay the custom text through the
    // selected reader and adopt only the state it can still prove.
    if (text.empty())
        return;
    // Some callers, such as lightweight firmware tests, do not install a
    // reader service. Without one, this session cannot learn script effects.
    if (m_gcode_reader_service == nullptr)
        return;

    // Start the reader with a snapshot of this session's current knowledge.
    // Omitting an unknown value is intentional: the reader must not infer a
    // coordinate, heater target, or tool selection that the writer does not
    // actually know.
    std::vector<raw_gcode_reader_event_item> items;
    items.reserve(13 + m_extruders.size() * 3);
    // A custom script is parsed as an independent input stream. Its first
    // physical line is therefore zero, regardless of its output position.
    items.push_back({RAW_GCODE_READER_ITEM_LINE_NUMBER, 0, 0.0});
    items.push_back({RAW_GCODE_READER_ITEM_READER_ID, 0, double(reader_state_id())});
    if (const std::optional<c_vec3d> position = m_gantry.position()) {
        items.push_back({RAW_GCODE_READER_ITEM_X, 0, position->x});
        items.push_back({RAW_GCODE_READER_ITEM_Y, 0, position->y});
        items.push_back({RAW_GCODE_READER_ITEM_Z, 0, position->z});
    }
    items.push_back({RAW_GCODE_READER_ITEM_UNITS_MM, 0, m_units_in_mm ? 1.0 : 0.0});
    items.push_back({RAW_GCODE_READER_ITEM_XYZ_ABSOLUTE, 0, m_xyz_relative_mode ? 0.0 : 1.0});
    items.push_back({RAW_GCODE_READER_ITEM_E_ABSOLUTE, 0, m_e_relative_mode ? 0.0 : 1.0});
    if (const std::optional<double> speed = m_gantry.encoded_speed())
        items.push_back({RAW_GCODE_READER_ITEM_FEEDRATE, 0, *speed * 60.0});
    if (m_current_extruder_idx) {
        // E coordinates belong to the currently selected extruder. Supplying
        // them for every tool would incorrectly claim that all E origins are
        // synchronized with the machine.
        const extruder_index_t tool_id = *m_current_extruder_idx;
        const uint32_t reader_target = static_cast<uint32_t>(tool_id);
        items.push_back({RAW_GCODE_READER_ITEM_ACTIVE_TOOL, 0, double(tool_id)});
        if (m_e_position_known)
            items.push_back({RAW_GCODE_READER_ITEM_E, reader_target,
                             current_extruder().extrusion_axis().position()});
    }
    for (const DefaultExtruder &tool : m_extruders) {
        append_known_temperature(items, RAW_GCODE_READER_ITEM_TOOL_TEMPERATURE, tool.id(),
                                 tool.heater().encoded_temperature());
        if (const std::optional<double> speed = tool.fan().encoded_speed_percent())
            items.push_back({RAW_GCODE_READER_ITEM_FAN_SPEED, tool.id(), *speed});
    }
    append_known_temperature(items, RAW_GCODE_READER_ITEM_BED_TEMPERATURE, 0,
                             m_printer.bed_heater().encoded_temperature());
    append_known_temperature(items, RAW_GCODE_READER_ITEM_CHAMBER_TEMPERATURE, 0,
                             m_printer.chamber_heater().encoded_temperature());
    append_reader_private_state(items);

    raw_gcode_reader_state initial = {};
    initial.items = items.empty() ? nullptr : items.data();
    initial.item_count = static_cast<uint32_t>(items.size());

    // The reader service copies the provider's final callback while it is
    // valid and returns a self-contained value; no parser-owned pointer escapes
    // the synchronous plugin invocation.
    const GCodeStateTracker tracked = m_gcode_reader_service->read(
        reader_plugin_id(), initial, text);
    if (tracked.reader_id() != reader_state_id())
        throw std::runtime_error("The G-code Reader returned state for another firmware identity.");

    const std::optional<double> units_mm = tracked.value(RAW_GCODE_READER_ITEM_UNITS_MM);
    const std::optional<double> xyz_absolute = tracked.value(RAW_GCODE_READER_ITEM_XYZ_ABSOLUTE);
    const std::optional<double> e_absolute = tracked.value(RAW_GCODE_READER_ITEM_E_ABSOLUTE);
    // Unknown modes deliberately force G21/G90 before the next generated move.
    m_units_in_mm = units_mm && *units_mm != 0.0;
    m_xyz_relative_mode = !xyz_absolute || *xyz_absolute == 0.0;
    m_e_relative_mode = !e_absolute || *e_absolute == 0.0;

    const std::optional<double> x = tracked.value(RAW_GCODE_READER_ITEM_X);
    const std::optional<double> y = tracked.value(RAW_GCODE_READER_ITEM_Y);
    const std::optional<double> z = tracked.value(RAW_GCODE_READER_ITEM_Z);
    // XYZ is a single coordinate. Keeping only two axes would create a
    // position that never existed, so any incomplete result invalidates it.
    if (x && y && z)
        m_gantry.set_position(c_vec3d{*x, *y, *z});
    else
        m_gantry.invalidate_position();

    const std::optional<double> feedrate = tracked.value(RAW_GCODE_READER_ITEM_FEEDRATE);
    m_gantry.synchronize_encoded_speed(feedrate ?
        std::optional<double>(*feedrate / 60.0) : std::optional<double>());

    const std::optional<double> active_tool = tracked.value(RAW_GCODE_READER_ITEM_ACTIVE_TOOL);
    // A reader may report a tool identifier that this print does not own.
    // Treat it as unknown instead of indexing outside m_extruders.
    if (active_tool && std::isfinite(*active_tool) &&
        *active_tool >= 0.0 &&
        *active_tool <= double((std::numeric_limits<extruder_index_t>::max)()) &&
        std::trunc(*active_tool) == *active_tool &&
        *active_tool < double(m_extruders.size()))
        m_current_extruder_idx = static_cast<extruder_index_t>(*active_tool);
    else
        m_current_extruder_idx.reset();
    settle_filament_usage();

    // Reconcile independent peripheral state for every known tool. A missing
    // item clears the cached acknowledgement rather than preserving a stale
    // command that may have been superseded by the script.
    for (DefaultExtruder &tool : m_extruders) {
        const std::optional<double> temperature = tracked.value(
            RAW_GCODE_READER_ITEM_TOOL_TEMPERATURE, tool.id());
        if (temperature) {
            const bool waited = tracked.known(
                RAW_GCODE_READER_ITEM_TOOL_TEMPERATURE_REACHED, tool.id());
            tool.heater().synchronize_after_external_gcode(
                reader_temperature(*temperature), waited);
        } else {
            tool.heater().clear_encoded();
            tool.heater().clear_encoded_with_wait();
        }
        const std::optional<double> fan = tracked.value(RAW_GCODE_READER_ITEM_FAN_SPEED, tool.id());
        if (fan)
            tool.fan().synchronize_encoded_after_external_gcode(fan);
        else {
            tool.fan().clear_encoded();
        }
        tool.extrusion_axis().set_relative_mode(m_e_relative_mode);
    }

    if (m_current_extruder_idx) {
        DefaultExtruder &tool = current_extruder();
        const std::optional<double> e = tracked.value(
            RAW_GCODE_READER_ITEM_E, *m_current_extruder_idx);
        if (e && !m_e_relative_mode) {
            // Keep the retraction and its scheduled extras exactly as the
            // explicit operations left them.
            tool.extrusion_axis().synchronize_after_external_gcode(
                *e, tool.extrusion_axis().retracted(), tool.extrusion_axis().restart_extra());
            m_e_position_known = true;
        } else {
            m_e_position_known = false;
        }
    } else {
        m_e_position_known = false;
    }

    // Bed and chamber heaters are global rather than tool-owned, but follow
    // the same rule: retain a target only when the reader returned one and
    // separately retain whether the script waited for it.
    const std::optional<double> bed_temperature = tracked.value(RAW_GCODE_READER_ITEM_BED_TEMPERATURE);
    if (bed_temperature) {
        const bool waited = tracked.known(RAW_GCODE_READER_ITEM_BED_TEMPERATURE_REACHED);
        m_printer.bed_heater().synchronize_after_external_gcode(
            reader_temperature(*bed_temperature), waited);
    } else {
        m_printer.bed_heater().clear_encoded();
        m_printer.bed_heater().clear_encoded_with_wait();
    }
    const std::optional<double> chamber_temperature = tracked.value(
        RAW_GCODE_READER_ITEM_CHAMBER_TEMPERATURE);
    if (chamber_temperature) {
        const bool waited = tracked.known(RAW_GCODE_READER_ITEM_CHAMBER_TEMPERATURE_REACHED);
        m_printer.chamber_heater().synchronize_after_external_gcode(
            reader_temperature(*chamber_temperature), waited);
    } else {
        m_printer.chamber_heater().clear_encoded();
        m_printer.chamber_heater().clear_encoded_with_wait();
    }
    synchronize_reader_private_state(tracked);
}

