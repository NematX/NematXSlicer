// Resolve a catalog ID or UINT32_MAX outside sentinel, close/open enabled labels
// and update the active ID; synthetic entries resolve to outside. Return owned
// label/marker text, or nothing for disabled/unchanged labels. Unknown IDs and
// encoder failures throw; catalog metadata remains session-owned.
// When the dialect asks for it (resets_extrusion_axis_after_object_end) and E is
// absolute, the end marker is followed by the axis-reset command and the logical E
// is zeroed with reset_E(): coordinates and rounding remainder restart at zero, while
// the retraction debt, restart extras and filament usage are kept. Callers must
// sequence this call before serializing the work that follows, since that work is
// prepared from the zeroed E.
// When the dialect answers a retraction depth (object_block_retract_length), a block
// that gets a firmware label is entered and left with the same debt: the complement is
// retracted before the start label (outside the block) and, up to the entry depth,
// before the end label (inside the block, so before the axis reset). Cancelling the
// block then does not change the filament state, wherever the plan retracted or did
// not retract at its edges. A tool change closes the block first (select_extruder()).
std::string DefaultGCodeFirmwareSession::transition_object(const uint32_t printing_catalog_id)
{
    if (m_object_label_style == ObjectLabelStyle::Disabled)
        return {};
    const uint32_t object_id = printing_catalog_id != uint32_t(-1) &&
        object_label(printing_catalog_id).is_synthetic ? uint32_t(-1) : printing_catalog_id;
    if (object_id == m_current_printing_catalog_id)
        return {};

    std::string output;
    const bool octoprint = m_object_label_style == ObjectLabelStyle::Octoprint ||
        m_object_label_style == ObjectLabelStyle::Both;
    const bool firmware = m_object_label_style == ObjectLabelStyle::Firmware ||
        m_object_label_style == ObjectLabelStyle::Both;
    if (m_current_printing_catalog_id != uint32_t(-1)) {
        const ObjectLabel &previous = object_label(m_current_printing_catalog_id);
        m_object_block_unretract_pending = false;
        const std::string end_label = firmware ? encode_object_end(previous) : std::string();
        // A block opened with a retraction depth is closed with the depth it was
        // entered with (inside the block, before the end label), so that it leaves
        // the filament as it found it whatever the plan did at its exit. The tool
        // is still the block's tool: select_extruder() closes the block before any
        // tool change. A block that ends deeper than its entry depth is left as is.
        if (!end_label.empty() && m_object_block_depth && m_current_extruder_idx)
            output += write_block_retraction(*m_object_block_depth);
        m_object_block_depth.reset();
        m_object_block_open = false;
        if (octoprint)
            output += "; stop printing object " + previous.name + "\n";
        if (firmware) {
            output += end_label;
            // The zero is established here, before the next move's E is prepared,
            // so that the logical E restarts from the emitted G92 E0.
            if (!m_e_relative_mode && m_current_extruder_idx &&
                resets_extrusion_axis_after_object_end(previous)) {
                output += encode_extrusion_axis_reset();
                current_extruder().extrusion_axis().reset_E();
                m_e_position_known = true;
            }
        }
    }
    // The dialect's pre-opening text runs outside either block. A nested request
    // to close the current object is consequently a no-op here.
    m_current_printing_catalog_id = uint32_t(-1);
    if (object_id != uint32_t(-1)) {
        const ObjectLabel &next = object_label(object_id);
        const std::string start_label = firmware ? encode_object_start(next) : std::string();
        if (!start_label.empty())
            output += write_before_object_start();
        m_current_printing_catalog_id = object_id;
        m_object_block_open = !start_label.empty();
        // A block that really gets a firmware label opens with the dialect's
        // retraction depth. The complement is written before the label, so it runs
        // even when the object is skipped and the block (which repays it) is not.
        if (!start_label.empty() && m_current_extruder_idx) {
            const double depth = object_block_retract_length(next, *m_current_extruder_idx);
            if (depth > 0.0) {
                output += write_block_retraction(depth);
                m_object_block_unretract_pending = true;
                // Entry depth: the tool's debt after the complement, i.e. the larger
                // of its previous debt and the requested depth.
                m_object_block_depth = current_extruder().extrusion_axis().retracted();
            }
        }
        if (octoprint)
            output += "; printing object " + next.name + "\n";
        output += start_label;
    }
    // Real IDs stay aligned with the plan; synthetic work uses the explicit
    // outside-object sentinel instead of a cancellable object identity.
    const int64_t marker_object_id = object_id == uint32_t(-1) ?
        -1 : int64_t(object_id);
    output += "; SLIC3R_OBJECT_INSTANCE_ID=" +
        std::to_string(marker_object_id) + "\n";
    return output;
}

