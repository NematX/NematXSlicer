/*
Translate an ordered printing plan into printer commands for a firmware session.
The file writer enters print, group, layer and tool boundaries; this session
walks each extrusion tree and returns the text to write at those boundaries.
The writer owns the file, while the session owns the machine state it encodes.

A tree leaf is an individual printable path or command. DEPOSIT is a leaf that
deposits a volume at one position rather than moving along a polyline. The plan's
catalogue identifies physical object instances and generated items such as towers.
These identities let the session label cancellable objects without labelling towers.

Standard PrintingPlan firmware implementation
=============================================

The implementation has two layers. ExtrusionWriterVisitor resolves inherited
properties while it walks one extrusion tree. DefaultGCodeFirmwareSession then
compares those requested values with its persistent machine state and encodes
only the Marlin output required to represent the requested state.
Stationary DEPOSIT leaves carry one point and a volume before the tool multiplier.
They use the same approach travel and marker order as paths, then emit an E-only
move at the filament speed of a line with their inherited flow and print speed.
The first generated approach uses lift_min, capped at max_print_height and
transformed by the gantry and tool Z corrections, as an absolute Z floor reached
vertically before XY movement, and descends only at the first path's start.
Inside a block opened with a retraction depth, the first deposit is preceded by the
block's explicit unretraction, like the first geometric leaf.
For scripts, a source extrusion is a plan extrusion linked to a sliced regional
island; its source layer height comes from that island, not from path attributes.
The session selects the first such height for a layer or tool group and updates
it again when an individual source extrusion begins.
In single-extruder multi-material (SEMM), logical tool IDs select filaments on
one physical extruder. Tool selection copies runtime state while preserving
each filament's configured conversions, speeds and device offsets.

Cancellation labels cover only catalog entries backed by source objects.
Synthetic entries, including wipe towers, close any active label and emit no
start label. Their extrusion role markers remain independent of object labels.
The optional pre-opening hook writes global dialect commands after the preceding
block is closed and before the next label, so cancelling an object cannot skip
those commands. A dialect can close the current block with transition_object's
outside sentinel before emitting such a command at another callback.
When a dialect closes object blocks before tool changes, the visitor remembers
the current tree's object and reopens its block before the next geometric leaf or
stationary deposit. Reopening follows the ordinary transition, including the dialect's pre-opening
commands and entry retraction, before the leaf prepares any extrusion coordinate.

Custom G-code temporarily hands control to text not generated by this session:

                                                    |
                                                    v
                                      proven final machine state
                                                    |
                                                    v
                                   reconcile or invalidate writer caches

The next generated move restores only the modes and coordinates which are
needed. Unknown Reader values are never replaced with guesses; their caches are
cleared so an explicit command is emitted before they are used again.

Every output fragment is generated before its corresponding state is marked as
encoded. If an encoder throws, the caller receives an error and the session
does not record the failed output as successfully generated.

Operation notes:
- cached writer state :  custom/script G-code :  selected GCodeReader

Representative direct calls (branches are not a timeline):

    DefaultGCodeFirmwareSession::begin_print()
        |-- setup()
        |-- plan.object_instance()
        `-- encode_object_definitions()

    DefaultGCodeFirmwareSession::write_extrusion_tree()
        `-- visitor.write()

    visit_leaf()
        |-- m_session.visit_extrusion_leaf()
        |-- m_session.write_deposit()
        `-- m_session.write_leaf_geometry()
*/

