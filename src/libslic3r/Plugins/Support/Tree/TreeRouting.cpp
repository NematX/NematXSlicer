// Routes the tree branches of one object: contacts from the shared helper, tips under them, influence areas propagated down the
// object layers, then the nodes of each layer. The context gives the cancellation checks and, through its STEP_SUPPORT payload, the
// pattern callbacks that sample the tips; it must come from the support step.
std::vector<RoutedTree> route_trees(const slic3r_api::Print &print, const slic3r_api::Object &object, const Common::SupportParams &params,
                                    const TreeSettings &settings, Common::GeneratedSupport &support, const plugin_run_context *context)
{
    generate_contacts(print, object, params, settings, support);
    const std::vector<TipSource> sources = tip_sources(object, settings, object.config(), support);
    if (sources.empty())
        return {};
    LayerIndex max_layer = 0;
    for (const TipSource &source : sources)
        max_layer = std::max(max_layer, source.layer);
    const Common::PatternService patterns(plugin_ctx_as_generate_support(context));
    TreeVolumes volumes(object, print, settings, support.storage, context);
    volumes.precalculate(max_layer);
    std::vector<SupportElements> move_bounds(object.layer_count());
    generate_initial_areas(volumes, settings, params, patterns, sources, move_bounds, support.storage, context);
    create_layer_pathing(volumes, settings, move_bounds, support.storage, context);
    create_nodes_from_area(volumes, settings, move_bounds, context);
    trim_contacts_to_placed_tips(move_bounds, sources, object, support);
    return build_trees(object, settings, move_bounds);
}

// Creates the top contact of every object layer that has support demand. The contact area is the demand minus the
// object layer below, grown by the XY distance of overhang outlines; the shared helper places the contact in Z and
// merges the close contacts. The areas of every layer are computed in one scratch storage; the contacts keep copies in the run storage.
static void generate_contacts(const slic3r_api::Print &print, const slic3r_api::Object &object, const Common::SupportParams &params,
                              const TreeSettings &settings, Common::GeneratedSupport &support)
{
    const slic3r_api::Config print_config = print.config();
    std::vector<slic3r_api::Layer> layers;
    for (uint32_t id = 0; id < object.layer_count(); ++id)
        layers.push_back(object.layer(id));
    with_scratch_storage([&](storage_handle *scratch) {
        for (uint32_t id = 1; id < layers.size(); ++id) {
            StoredExPolygonCollection islands_demand(scratch);
            for (uint32_t island = 0; island < layers[id].island_count(); ++island)
                islands_demand.append_copy_from(layers[id].island(island).support_demand());
            if (islands_demand.empty())
                continue;
            const StoredExPolygonCollection demand = expolygons_union(scratch, islands_demand);
            const StoredExPolygonCollection margin = expolygons_offset(scratch, layers[id - 1].slices(), double(float(settings.xy_min_distance)), CLIPPER_JOIN_MITER, 1.2);
            const StoredExPolygonCollection contact = expolygons_diff(scratch, demand, margin);
            if (contact.empty())
                continue;
            const Common::TopContactSlabs slabs = Common::add_top_contacts(layers, print_config, params, id, support);
            if (!slabs.contact)
                continue;
            store_top_contact(*slabs.contact, support.storage, scratch, contact, demand);
            if (slabs.bridge)
                store_top_contact(*slabs.bridge, support.storage, scratch, contact, demand);
        }
    });
    Common::merge_contacts(params, support);
}

// Gives a top contact its geometry: the contact area, which is also its printed polygons, and the demand it came from.
static void store_top_contact(Common::GeneratorLayer &slab, storage_handle *storage, storage_handle *scratch, const ExPolygonCollection &contact,
                              const ExPolygonCollection &overhang)
{
    slab.contact_polygons.emplace(storage);
    slab.overhang_polygons.emplace(storage);
    const StoredPolygonCollection contact_rings = to_polygons(scratch, contact);
    slab.polygons.copy_from(contact_rings);
    slab.contact_polygons->copy_from(contact_rings);
    const StoredPolygonCollection overhang_rings = to_polygons(scratch, overhang);
    slab.overhang_polygons->copy_from(overhang_rings);
}

// Lists where the tips of each object layer with top contacts start. The stack of interface slabs hangs under the contact extreme, so the tips
// start on the highest object layer that does not rise above the bottom of that stack. Without interface layers the stack is
// the contact extreme itself. The tips are free to move from their first step: the interface stack above them is always placed, so they
// need no straight column (the native support holds a tip only to replace the roof layers it could not place). The contacts of one
// object layer (a bridge and the normal contact, which the merge may keep apart, and the demand that the merge adds to a contact)
// share one source: its area is the union, and it starts from the lowest contact.
static std::vector<TipSource> tip_sources(const slic3r_api::Object &object, const TreeSettings &settings, const slic3r_api::Config &config,
                                          const Common::GeneratedSupport &support)
{
    storage_handle *storage = support.storage;
    const coord_t step = settings.dense_slab_height;
    const int32_t interfaces = std::max(0, config.get("support_material_interface_layers").get_int());
    constexpr size_t no_source = std::numeric_limits<size_t>::max();
    std::vector<size_t> source_of_layer(object.layer_count(), no_source);
    std::vector<TipSource> sources;
    // The scratch storage holds the unions of the contacts and of the sources; the sources and the parts live in the run storage.
    std::vector<TipSource> parts;
    with_scratch_storage([&](storage_handle *scratch) {
        // The top contacts are sorted by print Z, so the first contact of an object layer is its lowest one.
        for (const Common::GeneratorLayer *contact : support.top) {
            const StoredPolygonCollection &area = *contact->contact_polygons;
            size_t &source = source_of_layer[contact->object_above];
            if (source != no_source) {
                StoredPolygonCollection united = polygons_union(scratch, sources[source].area, area);
                sources[source].area.move_from(united);
                continue;
            }
            source = sources.size();
            const coord_t stack_bottom = contact->extreme_z() - coord_t(interfaces) * step;
            LayerIndex layer = 0;
            for (LayerIndex idx = 0; idx < LayerIndex(object.layer_count()) && object.layer(idx).print_z() <= stack_bottom; ++ idx)
                layer = idx;
            sources.push_back(TipSource{ area.readonly().clone(storage), layer, contact->object_above });
        }
        // Each connected part of a contact area is a source of its own, so that a part without a placed tip is removed alone.
        for (const TipSource &source : sources) {
            const StoredExPolygonCollection united = expolygons_union(scratch, source.area);
            for (uint32_t idx = 0; idx < united.size(); ++idx)
                parts.push_back(TipSource{ expolygon_rings(storage, united.at(idx)), source.layer, source.object_above });
        }
    });
    return parts;
}

static StoredPolygonCollection expolygon_rings(storage_handle *storage, const slic3r_api::ExPolygon &expolygon)
{
    StoredPolygonCollection rings(storage);
    rings.push_back(expolygon.contour());
    for (const slic3r_api::Polygon hole : expolygon.holes())
        rings.push_back(hole);
    return rings;
}

// A part of a top contact that no placed tip reaches is cut from the contact, since its roof would have no branch under it.
static void trim_contacts_to_placed_tips(const std::vector<SupportElements> &move_bounds, const std::vector<TipSource> &sources,
                                         const slic3r_api::Object &object, Common::GeneratedSupport &support)
{
    std::vector<bool> reached(sources.size(), false);
    for (const SupportElements &layer : move_bounds)
        for (const SupportElement &elem : layer)
            if (elem.tip_source < sources.size() && elem.state.result_on_layer_is_set())
                reached[elem.tip_source] = true;
    with_scratch_storage([&](storage_handle *scratch) {
        // The areas of the reached sources, by object layer.
        std::vector<StoredPolygonCollection> placed;
        for (uint32_t layer = 0; layer < object.layer_count(); ++layer)
            placed.emplace_back(scratch);
        for (size_t idx = 0; idx < sources.size(); ++idx)
            if (reached[idx])
                placed[sources[idx].object_above].append_copy_from(sources[idx].area);
        for (Common::GeneratorLayer *contact : support.top) {
            const StoredPolygonCollection reached_area = polygons_union(scratch, placed[contact->object_above]);
            StoredPolygonCollection kept = polygons_intersection(scratch, contact->polygons, reached_area);
            contact->polygons.move_from(kept);
            StoredPolygonCollection kept_contact = polygons_intersection(scratch, *contact->contact_polygons, reached_area);
            contact->contact_polygons->move_from(kept_contact);
        }
    });
    support.top.erase(std::remove_if(support.top.begin(), support.top.end(),
        [](const Common::GeneratorLayer *contact) { return contact->polygons.empty(); }), support.top.end());
}

// Inserts the tips of one object as influence areas on their object layer. The tip sources are sampled in parallel, so the
// insertions are guarded; a point already covered by a tip of the same layer is not inserted twice. The influence area of a tip is
// allocated in the storage given (the run storage, since the element outlives the jobs).
class TipPlacer {
public:
    TipPlacer(const TreeSettings &config, bool min_xy_dist, std::vector<SupportElements> &move_bounds, storage_handle *storage);
    // Insert every point of the lines as a tip on insert_layer; source is the index of the tip source that the tips belong to.
    void add_points_along_lines(const LineInformations &lines, LayerIndex insert_layer, size_t source);

private:
    // Insert one point as a tip with a small base circle, unless a tip already covers it.
    void add_point(const std::pair<c_point, LineStatus> &point, LayerIndex insert_layer, bool skip_ovalisation, size_t source);

    const TreeSettings &m_config;
    const bool m_min_xy_dist;
    std::vector<SupportElements> &m_move_bounds;
    std::mutex m_mutex;
    std::vector<std::unordered_set<c_point, PointHash, PointEqual>> m_already_inserted;
    storage_handle *m_storage;
    // The influence area of a new tip is this circle, centred on the tip.
    std::vector<c_point> m_base_circle;
};

TipPlacer::TipPlacer(const TreeSettings &config, bool min_xy_dist, std::vector<SupportElements> &move_bounds, storage_handle *storage) :
    m_config(config), m_min_xy_dist(min_xy_dist), m_move_bounds(move_bounds),
    m_already_inserted(move_bounds.size()), m_storage(storage)
{
    m_base_circle = make_circle(scale_d(0.01), SUPPORT_TREE_CIRCLE_RESOLUTION);
}

// What the job of every tip source reads: the shared inputs (read only), the values computed once for all sources, and the placer,
// which locks its own insertions.
struct TipPlacement {
    const TreeVolumes &volumes;
    const TreeSettings &config;
    const Common::PatternService &patterns;
    const std::vector<TipSource> &sources;
    TipPlacer &placer;
    bool min_xy_dist;
    // The distance along a line between two tips, before the line is thinned.
    coord_t connect_length;
    // The distance along x at which a circle of radius min_radius dips by half a line width.
    coord_t circle_length_to_half_linewidth_change;
    // Extra outset that compensates for the tip radius, and for the XY distance when the XY distance overrides the Z distance.
    coord_t extra_outset;
    // The recipe of the pattern fill of each source (the layer of the fill differs per source), built once before the jobs.
    std::vector<raw_infill_pattern_params> recipes;
    // The context of the step: the job checks its cancellation after each pattern call.
    const plugin_run_context *context;
};

// Places the tips under every tip source. The contact area is grown into the free space of the tip layer as far as the
// tip radius needs, then each of its parts is sampled along lines spaced by the branch distance.
static void generate_initial_areas(const TreeVolumes &volumes, const TreeSettings &config, const Common::SupportParams &params,
                                   const Common::PatternService &patterns, const std::vector<TipSource> &sources,
                                   std::vector<SupportElements> &move_bounds, storage_handle *run_storage, const plugin_run_context *context)
{
    const bool min_xy_dist = config.xy_distance > config.xy_min_distance;
    TipPlacer placer(config, min_xy_dist, move_bounds, run_storage);
    const coord_t connect_length = (config.support_line_width * 100. / config.top_rate) + std::max(2. * config.min_radius - 1.0 * config.support_line_width, 0.0);
    // As r*r=x*x+y*y (circle equation): the distance along x at which a circle of radius min_radius dips by half a line width.
    const coord_t circle_length_to_half_linewidth_change = config.min_radius < config.support_line_width ?
        config.min_radius / 2 :
        scale_i(sqrt(sqr(unscaled(config.min_radius)) - sqr(unscaled(config.min_radius - config.support_line_width / 2))));
    // Extra outset that compensates for the tip radius, and for the XY distance when the XY distance overrides the Z distance.
    const coord_t extra_outset = std::max(coord_t(0), config.min_radius - config.support_line_width / 2) + (min_xy_dist ? config.support_line_width / 2 : 0);
    // The recipe of the lines: the flow and spacing of the base, the density that makes the lines one branch distance apart, and its angle.
    Common::PatternService::Fill fill;
    fill.flow = params.base_flow;
    fill.spacing = params.base_flow_mm.spacing;
    fill.density = float(scale_d(fill.spacing) / (scale_d(fill.spacing) + float(config.branch_distance)));
    fill.angle = params.base_angle;
    const infill_pattern_runtime_id pattern_id = patterns.resolve(params.base_pattern_id);
    std::vector<raw_infill_pattern_params> recipes;
    for (const TipSource &source : sources) {
        fill.layer_id = uint32_t(source.layer);
        recipes.push_back(Common::PatternService::recipe(pattern_id, fill));
    }
    const TipPlacement placement{ volumes, config, patterns, sources, placer, min_xy_dist, connect_length,
        circle_length_to_half_linewidth_change, extra_outset, std::move(recipes), context };
    // FIXME(perf): one job per source, as the legacy loop did (every job does a pattern call and several Clipper operations, so the job is
    // not small); a source that is cheap against the cost of its scratch storage would call for chunks of sources. To measure.
    slic3r_api::parallel_for_storage_with_progress(0, uint32_t(sources.size()), context, nullptr, &place_source_tips, &placement);
}

static void place_source_tips(uint32_t source_idx, storage_handle *scratch, const TipPlacement *placement)
{
    const TipSource &source = placement->sources[source_idx];
    const StoredPolygonCollection overhang_regular = supported_overhang(scratch, *placement, source);
    const StoredExPolygonCollection parts = expolygons_union(scratch, overhang_regular);
    for (uint32_t part_idx = 0; part_idx < parts.size(); ++part_idx) {
        const StoredPolygonCollection part_area = expolygon_rings(scratch, parts.at(part_idx));
        const Lines lines = tip_lines(scratch, *placement, source_idx, part_area);
        // A pattern error or a cancellation stops the step: no further part; the jobs still to run stop at their next check.
        slic3r_api::throw_if_cancelled(placement->context);
        const LineInformations overhang_lines = convert_lines_to_internal(placement->volumes, placement->config, lines, source.layer);
        placement->placer.add_points_along_lines(overhang_lines, source.layer, source_idx);
    }
}

static StoredPolygonCollection supported_overhang(storage_handle *scratch, const TipPlacement &placement, const TipSource &source)
{
    using AvoidanceType = TreeVolumes::AvoidanceType;
    const TreeSettings &config = placement.config;
    const LayerIndex layer_idx = source.layer;
    // The least restrictive forbidden area for the tip radius. The offset prevents rounding errors down the line: points placed
    // directly on the line of the forbidden area may not be added otherwise.
    const StoredPolygonCollection &relevant_forbidden_raw = config.support_rests_on_model ?
        placement.volumes.getCollision(config.min_radius, layer_idx, placement.min_xy_dist) :
        placement.volumes.getAvoidance(config.min_radius, layer_idx, AvoidanceType::Fast, false, placement.min_xy_dist);
    const StoredExPolygonCollection forbidden_regions = expolygons_union(scratch, relevant_forbidden_raw);
    const StoredPolygonCollection relevant_forbidden = polygons_offset(scratch, forbidden_regions, scale_d(0.005), CLIPPER_JOIN_MITER, 1.2);
    StoredPolygonCollection overhang_regular = safe_offset_inc(scratch, source.area, 0, relevant_forbidden, config.min_radius * 1.75 + config.xy_min_distance, 0, 1);
    const StoredExPolygonCollection supported_regions = expolygons_union(scratch, overhang_regular);
    const StoredPolygonCollection supported_grown = polygons_offset(scratch, supported_regions, config.support_line_width * 0.5, CLIPPER_JOIN_MITER, 1.2);
    const StoredPolygonCollection not_supported = polygons_diff(scratch, source.area, supported_grown);
    StoredPolygonCollection remaining_overhang = polygons_intersection(scratch, not_supported, relevant_forbidden);
    // Grow the supported area in steps, while the remaining overhang still needs support.
    for (coord_t extra_total_offset_acc = 0; ! remaining_overhang.empty() && extra_total_offset_acc + config.support_line_width / 8 < placement.extra_outset; ) {
        const coord_t offset_current_step = std::min(
            extra_total_offset_acc + 2 * config.support_line_width > config.min_radius ?
                config.support_line_width / 8 :
                placement.circle_length_to_half_linewidth_change,
            placement.extra_outset - extra_total_offset_acc);
        extra_total_offset_acc += offset_current_step;
        const StoredPolygonCollection &raw_collision = placement.volumes.getCollision(0, layer_idx, true);
        const coord_t offset_step = config.xy_min_distance + config.support_line_width;
        // Reduce the remaining overhang by the areas already supported, then extend the supported area by what is left.
        remaining_overhang = polygons_diff(scratch, remaining_overhang, safe_offset_inc(scratch, overhang_regular, coord_t(1.5 * extra_total_offset_acc), raw_collision, offset_step, 0, 1));
        overhang_regular = polygons_union(scratch, overhang_regular, polygons_diff(scratch, safe_offset_inc(scratch, remaining_overhang, extra_total_offset_acc, raw_collision, offset_step, 0, 1), relevant_forbidden));
    }
    return overhang_regular;
}

static Lines tip_lines(storage_handle *scratch, const TipPlacement &placement, uint32_t source_idx, const PolygonCollection &part_area)
{
    const TreeSettings &config = placement.config;
    Lines lines = ensure_maximum_distance_polyline(scratch, generate_support_infill_lines(scratch, placement, placement.recipes[source_idx], part_area), placement.connect_length, 1);
    size_t point_count = 0;
    for (const std::vector<c_point> &line : lines)
        point_count += line.size();
    const size_t min_support_points = std::max(coord_t(1), std::min(coord_t(3), coord_t(total_length(part_area) / placement.connect_length)));
    if (point_count > min_support_points)
        return lines;
    // Too few points to hold the part: sample the outline instead, so that the tips support the outer wall.
    const StoredExPolygonCollection part_regions = expolygons_union(scratch, part_area);
    const StoredPolygonCollection reduced_overhang_area = polygons_offset(scratch, part_regions, - config.support_line_width / 2.2, CLIPPER_JOIN_MITER, 1.2);
    bool use_reduced_area = false;
    if (! reduced_overhang_area.empty()) {
        const StoredExPolygonCollection removed_regions = expolygons_diff(scratch, part_area, reduced_overhang_area);
        const StoredPolygonCollection thin_parts = polygons_offset(scratch, removed_regions,
            std::max(config.support_line_width, placement.connect_length), CLIPPER_JOIN_MITER, 1.2);
        use_reduced_area = polygons_area(thin_parts) < sqr(scale_d(0.001));
    }
    const StoredPolylineCollection outline = to_polylines(scratch, use_reduced_area ? static_cast<const PolygonCollection &>(reduced_overhang_area) : part_area);
    Lines outline_lines;
    for (uint32_t idx = 0; idx < outline.size(); ++idx)
        outline_lines.push_back(outline.at(idx).points());
    return ensure_maximum_distance_polyline(scratch, outline_lines, placement.connect_length, min_support_points);
}

void TipPlacer::add_points_along_lines(const LineInformations &lines, LayerIndex insert_layer, size_t source)
{
    for (const LineInformation &line : lines) {
        // A line of many tips simulates a support pattern, so its tips keep their ovalisation disabled to stay a clean line.
        const bool disable_ovalistation = m_config.min_radius < 3 * m_config.support_line_width && line.size() > 5;
        for (const std::pair<c_point, LineStatus> &point_data : line)
            add_point(point_data, insert_layer, disable_ovalistation, source);
    }
}

void TipPlacer::add_point(const std::pair<c_point, LineStatus> &point, LayerIndex insert_layer, bool skip_ovalisation, size_t source)
{
    const bool to_bp = point.second == LineStatus::TO_BP || point.second == LineStatus::TO_BP_SAFE;
    const bool gracious = to_bp || point.second == LineStatus::TO_MODEL_GRACIOUS || point.second == LineStatus::TO_MODEL_GRACIOUS_SAFE;
    const bool safe_radius = point.second == LineStatus::TO_BP_SAFE || point.second == LineStatus::TO_MODEL_GRACIOUS_SAFE;
    if (! m_config.support_rests_on_model && ! to_bp) {
        BOOST_LOG_TRIVIAL(warning) << "Tried to add an invalid support point";
        return;
    }
    const c_point position = point.first;
    // The influence area of the tip: the base circle moved onto the tip, in the run storage. It is built before the lock is taken,
    // so that no storage call is made inside it; a tip that is refused frees it again.
    std::vector<c_point> circle_points = m_base_circle;
    for (c_point &circle_point : circle_points)
        circle_point = circle_point + point.first;
    slic3r_api::StoredPolygon circle_ring(m_storage);
    circle_ring.insert_array(0, circle_points.data(), uint32_t(circle_points.size()));
    StoredPolygonCollection circle(m_storage);
    circle.push_back(circle_ring);
    // Points closer than a tenth of the tip radius are the same tip for the purpose of the insertion.
    const c_point hash_pos = point.first / ((m_config.min_radius + 1) / 10);
    std::lock_guard<std::mutex> critical_section(m_mutex);
    if (m_already_inserted[insert_layer].count(hash_pos))
        return;
    m_already_inserted[insert_layer].emplace(hash_pos);
    SupportElementState state;
    state.target_height = insert_layer;
    state.target_position = position;
    state.next_position = position;
    state.layer_idx = insert_layer;
    state.radius_gain = 0;
    state.to_buildplate = to_bp;
    state.distance_to_top = 0;
    state.result_on_layer = position;
    state.increased_to_model_radius = 0;
    state.to_model_gracious = gracious;
    state.foot_gain = 0;
    state.use_min_xy_dist = m_min_xy_dist;
    state.can_use_safe_radius = safe_radius;
    state.skip_ovalisation = skip_ovalisation;
    m_move_bounds[insert_layer].emplace_back(state, std::move(circle)).tip_source = source;
}

/*!
 * \brief Eensures that every line segment is about distance in length. The resulting lines may differ from the original but all points are on the original
 *
 * \param input[in] The lines on which evenly spaced points should be placed.
 * \param distance[in] The distance the points should be from each other.
 * \param min_points[in] The amount of points that have to be placed. If not enough can be placed the distance will be reduced to place this many points.
 * \return The lines containing the evenly spaced points. Does not represent an area, more a collection of points on lines.
 */
[[nodiscard]] static Lines ensure_maximum_distance_polyline(storage_handle *scratch, const Lines &input, double distance, size_t min_points)
{
    Lines result;
    for (std::vector<c_point> part : input) {
        if (part.empty())
            continue;

        double len = polyline_length(part);
        std::vector<c_point> line;
        double current_distance = std::max(distance, scale_d(0.1));
        if (len < 2 * distance && min_points <= 1)
        {
            // Insert the opposite point of the first one.
            //FIXME pretty expensive
            slic3r_api::StoredPolyline half(scratch);
            for (const c_point &point : part)
                half.push_back(point);
            half.clip_end(len / 2);
            line.push_back(half.back());
        }
        else
        {
            size_t optimal_end_index = part.size() - 1;

            if (part.front() == part.back()) {
                size_t optimal_start_index = 0;
                // If the polyline was a polygon, there is a high chance it was an overhang. Overhangs that are <60° tend to be very thin areas, so lets get the beginning and end of them and ensure that they are supported.
                // The first point of the line will always be supported, so rotate the order of points in this polyline that one of the two corresponding points that are furthest from each other is in the beginning.
                // The other will be manually added (optimal_end_index)
                coord_t max_dist2_between_vertecies = 0;
                for (size_t idx = 0; idx < part.size() - 1; ++ idx) {
                    for (size_t inner_idx = 0; inner_idx < part.size() - 1; inner_idx++) {
                        if (to_vec2d(part[idx] - part[inner_idx]).squaredNorm() > max_dist2_between_vertecies) {
                            optimal_start_index = idx;
                            optimal_end_index = inner_idx;
                            max_dist2_between_vertecies = to_vec2d(part[idx] - part[inner_idx]).squaredNorm();
                        }
                    }
                }
                std::rotate(part.begin(), part.begin() + optimal_start_index, part.end() - 1);
                part[part.size() - 1] = part[0]; // restore that property that this polyline ends where it started.
                optimal_end_index = (part.size() + optimal_end_index - optimal_start_index - 1) % (part.size() - 1);
            }

            while (line.size() < min_points && current_distance >= scale_d(0.1))
            {
                line.clear();
                c_point current_point = part[0];
                line.push_back(part[0]);
                if (min_points > 1 || slic3r_api::norm(part[0] - part[optimal_end_index]) > current_distance)
                    line.push_back(part[optimal_end_index]);
                size_t current_index = 0;
                std::optional<std::pair<c_point, size_t>> next_point;
                double next_distance = current_distance;
                // Get points so that at least min_points are added and they each are current_distance away from each other. If that is impossible, decrease current_distance a bit.
                // The input are lines, that means that the line from the last to the first vertex does not have to exist, so exclude all points that are on this line!
                while ((next_point = polyline_sample_next_point_at_distance(part, current_point, current_index, next_distance))) {
                    // Not every point that is distance away, is valid, as it may be much closer to another point. This is especially the case when the overhang is very thin.
                    // So this ensures that the points are actually a certain distance from each other.
                    // This assurance is only made on a per polygon basis, as different but close polygon may not be able to use support below the other polygon.
                    double min_distance_to_existing_point = std::numeric_limits<double>::max();
                    for (const c_point &p : line)
                        min_distance_to_existing_point = std::min(min_distance_to_existing_point, slic3r_api::norm(p - next_point->first));
                    if (min_distance_to_existing_point >= current_distance) {
                        // viable point was found. Add to possible result.
                        line.push_back(next_point->first);
                        current_point = next_point->first;
                        current_index = next_point->second;
                        next_distance = current_distance;
                    } else {
                        if (current_point == next_point->first) {
                            // In case a fixpoint is encountered, better aggressively overcompensate so the code does not become stuck here...
                            BOOST_LOG_TRIVIAL(warning) << "Tree Support: Encountered a fixpoint in polyline_sample_next_point_at_distance. This is expected to happen if the distance (currently " << next_distance <<
                                ") is smaller than 100";
                            BOOST_LOG_TRIVIAL(error) << "Encountered issue while placing tips. Some tips may be missing."sv;
                            if (next_distance > 2 * current_distance)
                                // This case should never happen, but better safe than sorry.
                                break;
                            next_distance += current_distance;
                            continue;
                        }
                        // if the point was too close, the next possible viable point is at least distance-min_distance_to_existing_point away from the one that was just checked.
                        next_distance = std::max(current_distance - min_distance_to_existing_point, scale_d(0.1));
                        current_point = next_point->first;
                        current_index = next_point->second;
                    }
                }
                current_distance *= 0.9;
            }
        }
        result.emplace_back(std::move(line));
    }
    return result;
}

static double polyline_length(const std::vector<c_point> &polyline)
{
    double total = 0.;
    for (size_t idx = 1; idx < polyline.size(); ++idx)
        total += slic3r_api::norm(polyline[idx] - polyline[idx - 1]);
    return total;
}

// Ported from CURA's PolygonUtils::getNextPointWithDistance()
// Sample a next point at distance "dist" from start_pt on polyline segment (start_idx, start_idx + 1).
// Returns sample point and start index of its segment on polyline if such sample exists.
static std::optional<std::pair<c_point, size_t>> polyline_sample_next_point_at_distance(const std::vector<c_point> &polyline, c_point start_pt, size_t start_idx, double dist)
{
    const double                dist2  = sqr(dist);
    const int64_t               dist2i = int64_t(dist2);
    static constexpr const double eps  = scale_d(0.01);

    for (size_t i = start_idx + 1; i < polyline.size(); ++ i) {
        const c_point p1 = polyline[i];
        if (squared_norm(p1 - start_pt) >= dist2i) {
            // The end point is outside the circle with center "start_pt" and radius "dist".
            const c_point p0 = polyline[i - 1];
            Vec2d         v   = to_vec2d(p1 - p0);
            double        l2v = v.squaredNorm();
            if (l2v < sqr(eps)) {
                // Very short segment.
                c_point c = (p0 + p1) / 2;
                if (std::abs(slic3r_api::norm(start_pt - c) - dist) < eps)
                    return std::pair<c_point, size_t>{ c, i - 1 };
                else
                    continue;
            }
            Vec2d p0f = to_vec2d(start_pt - p0);
            // Foot point of start_pt into v.
            Vec2d foot_pt = v * (p0f.dot(v) / l2v);
            // Vector from foot point of "start_pt" to "start_pt".
            Vec2d xf = p0f - foot_pt;
            // Squared distance of "start_pt" from the ray (p0, p1).
            double l2_from_line = xf.squaredNorm();
            // Squared distance of an intersection point of a circle with center at the foot point.
            if (double l2_intersection = dist2 - l2_from_line;
                l2_intersection > - SCALED_EPSILON) {
                // The ray (p0, p1) touches or intersects a circle centered at "start_pt" with radius "dist".
                // Distance of the circle intersection point from the foot point.
                l2_intersection = std::max(l2_intersection, 0.);
                if ((v - foot_pt).squaredNorm() >= l2_intersection) {
                    // Intersection of the circle with the segment (p0, p1) is on the right side (close to p1) from the foot point.
                    const c_point p = p0 + truncated_point(foot_pt + v * sqrt(l2_intersection / l2v));
                    return std::pair<c_point, size_t>{ p, i - 1 };
                }
            }
        }
    }
    return {};
}

/*!
 * \brief Returns the lines of the support pattern that cover the given area, for the tips to sample.
 *
 * The lines come from the INFILL_PATTERN plugin of the base pattern, called through the pattern callbacks of the support step: a
 * call that the host reports as failed gives no line for that part.
 *
 * \param polygon[in] The area that has to be filled with infill.
 * \param recipe[in] The fill recipe of the tip source (pattern, flow, density, angle and layer).
 *
 * \return The points of the resulting infill lines, in the order the pattern generated them.
 */
static Lines generate_support_infill_lines(storage_handle *scratch, const TipPlacement &placement, const raw_infill_pattern_params &recipe, const PolygonCollection &polygon)
{
    Lines out;
    const StoredExPolygonCollection areas = expolygons_union(scratch, polygon);
    for (uint32_t idx = 0; idx < areas.size(); ++idx) {
        Lines lines = placement.patterns.fill_lines(scratch, areas.at(idx), recipe);
        // After each pattern call, before the next one and before the contour fallback: a failed call has requested the cancellation.
        slic3r_api::throw_if_cancelled(placement.context);
        std::move(lines.begin(), lines.end(), std::back_inserter(out));
    }
    return out;
}

/*!
 * \brief Converts the lines into the internal format.
 *
 * \param polylines[in] The lines that will be converted.
 * \param layer_idx[in] The current layer.
 * \return All lines of the \p polylines object, with information for each point regarding in which avoidance it is currently valid in.
 */
// Called by place_source_tips(), the job of generate_initial_areas().
[[nodiscard]] static LineInformations convert_lines_to_internal(
    const TreeVolumes &volumes, const TreeSettings &config,
    const Lines &polylines, LayerIndex layer_idx)
{
    const bool min_xy_dist = config.xy_distance > config.xy_min_distance;

    LineInformations result;
    // Also checks if the position is valid, if it is NOT, it deletes that point
    for (const std::vector<c_point> &line : polylines) {
        LineInformation res_line;
        for (const c_point &p : line) {
            if (! point_in_polygons(volumes.getAvoidance(config.min_radius, layer_idx, TreeVolumes::AvoidanceType::FastSafe, false, min_xy_dist), p))
                res_line.emplace_back(p, LineStatus::TO_BP_SAFE);
            else if (! point_in_polygons(volumes.getAvoidance(config.min_radius, layer_idx, TreeVolumes::AvoidanceType::Fast, false, min_xy_dist), p))
                res_line.emplace_back(p, LineStatus::TO_BP);
            else if (config.support_rests_on_model && ! point_in_polygons(volumes.getAvoidance(config.min_radius, layer_idx, TreeVolumes::AvoidanceType::FastSafe, true, min_xy_dist), p))
                res_line.emplace_back(p, LineStatus::TO_MODEL_GRACIOUS_SAFE);
            else if (config.support_rests_on_model && ! point_in_polygons(volumes.getAvoidance(config.min_radius, layer_idx, TreeVolumes::AvoidanceType::Fast, true, min_xy_dist), p))
                res_line.emplace_back(p, LineStatus::TO_MODEL_GRACIOUS);
            else if (config.support_rests_on_model && ! point_in_polygons(volumes.getCollision(config.min_radius, layer_idx, min_xy_dist), p))
                res_line.emplace_back(p, LineStatus::TO_MODEL);
            else if (!res_line.empty()) {
                result.emplace_back(res_line);
                res_line.clear();
            }
        }
        if (!res_line.empty()) {
            result.emplace_back(res_line);
            res_line.clear();
        }
    }

    return result;
}

/*!
 * \brief Offsets (increases the area of) a polygons object in multiple steps to ensure that it does not lag through over a given obstacle.
 * The offset is cut into steps of at most safe_step_size, and the obstacle is subtracted after each step, so that the area cannot jump over a
 * thin obstacle. The part of the distance that is not checked against the obstacle is offset last, in one piece.
 *
 * All distances are scaled units (coord_t). Round joins are used; the arc tolerance of the round offset is the 0.01 mm that this function
 * passes in the miter_limit argument of polygons_offset() (that argument is the arc tolerance for round joins, see TreeGeometry.hpp).
 * The result is simplified (0.015 mm) after the offsets, and every step reuses the collision trimmed to the box of the area.
 *
 * \param storage[in] The storage that owns the result and the temporary collections.
 * \param me[in] PolygonCollection view of the polygons that have to be offset.
 * \param distance[in] The distance by which me should be offset. Expects values >=0; 0 only unites (and subtracts the collision when last_step_offset_without_check is 0).
 * \param collision[in] The area representing obstacles.
 * \param safe_step_size[in] The largest distance offset in one step before the collision is subtracted. Must be >0 when distance is >0 (a step size of 0 divides by zero); a negative value is an error and gives the unchecked result.
 * \param last_step_offset_without_check[in] The maximum of the remainder that is offset in one piece, without a collision check after it (the area is subtracted once at the end when this is 0, or when the remainder is larger than it). Expects values >=0; 0 means every part of the distance is checked. Example: distance 10 mm, step 3 mm, threshold 2 mm gives three checked steps and 1 mm unchecked.
 * \param min_amount_offset[in] How many steps have to be done at least. As this uses round offset this increases the amount of vertices, which may be required if Polygons get very small.
 * \return The offset polygons, as a StoredPolygonCollection owned by storage.
 */
[[nodiscard]] static StoredPolygonCollection safe_offset_inc(storage_handle *storage, const PolygonCollection &me, coord_t distance, const PolygonCollection &collision, coord_t safe_step_size, coord_t last_step_offset_without_check, size_t min_amount_offset)
{
    bool do_final_difference = last_step_offset_without_check == 0;
    StoredPolygonCollection ret = safe_union(storage, me); // ensure sane input

    // Trim the collision polygons with the region of interest for diff() efficiency.
    StoredPolygonCollection collision_trimmed_buffer(storage);
    const std::function<const StoredPolygonCollection &()> collision_trimmed = [&collision_trimmed_buffer, &collision, &ret, distance, storage]() -> const StoredPolygonCollection & {
        // Nothing to trim against when the subject is empty (it has no box); the difference of an empty subject is empty anyway.
        if (collision_trimmed_buffer.empty() && ! collision.empty() && ! ret.empty())
            collision_trimmed_buffer = clip_polygons_with_subject_bbox(storage, collision, bounding_box_inflated(polygons_bounding_box(ret), coord_t(std::max(coord_t(0), distance) + SCALED_EPSILON)));
        return collision_trimmed_buffer;
    };

    if (distance == 0)
        return do_final_difference ? polygons_diff(storage, ret, collision_trimmed()) : polygons_union(storage, ret);
    if (safe_step_size < 0 || last_step_offset_without_check < 0) {
        BOOST_LOG_TRIVIAL(error) << "Offset increase got invalid parameter!";
        BOOST_LOG_TRIVIAL(error) << "Negative offset distance... How did you manage this ?"sv;
        return do_final_difference ? polygons_diff(storage, ret, collision_trimmed()) : polygons_union(storage, ret);
    }

    coord_t step_size = safe_step_size;
    int     steps = distance > last_step_offset_without_check ? (distance - last_step_offset_without_check) / step_size : 0;
    if (distance - steps * step_size > last_step_offset_without_check) {
        if ((steps + 1) * step_size <= distance)
            // This will be the case when last_step_offset_without_check >= safe_step_size
            ++ steps;
        else
            do_final_difference = true;
    }
    if (steps + (distance < last_step_offset_without_check || (distance % step_size) != 0) < int(min_amount_offset) && min_amount_offset > 1) {
        // yes one can add a bool as the standard specifies that a result from compare operators has to be 0 or 1
        // reduce the stepsize to ensure it is offset the required amount of times
        step_size = distance / min_amount_offset;
        if (step_size >= safe_step_size) {
            // effectivly reduce last_step_offset_without_check
            step_size = safe_step_size;
            steps = min_amount_offset;
        } else
            steps = distance / step_size;
    }
    // offset in steps
    for (int i = 0; i < steps; ++ i) {
        // The trimmed collision is requested before the offset, so that its box is the one of the ring before the offset.
        const StoredPolygonCollection &trimmed = collision_trimmed();
        ret = polygons_diff(storage, polygons_offset(storage, ret, step_size, CLIPPER_JOIN_ROUND, scale_d(0.01)), trimmed);
        // ensure that if many offsets are done the performance does not suffer extremely by the new vertices of jtRound.
        if (i % 10 == 7)
            ret = slic3r_api::polygons_simplify(storage, ret, scale_d(0.015));
    }
    // offset the remainder
    float last_offset = distance - steps * step_size;
    if (last_offset > SCALED_EPSILON)
        ret = polygons_offset(storage, ret, distance - steps * step_size, CLIPPER_JOIN_ROUND, scale_d(0.01));
    ret = slic3r_api::polygons_simplify(storage, ret, scale_d(0.015));

    if (do_final_difference)
        ret = polygons_diff(storage, ret, collision_trimmed());
    return polygons_union(storage, ret);
}

/*!
 * \brief Unions two polygon collections. Ensures that if the input is non empty that the output also will be non empty.
 * \param storage[in] The storage that owns the result and the temporary collections.
 * \param first[in] The first PolygonCollection view.
 * \param second[in] The second PolygonCollection view.
 * \return The union of both collections, as a StoredPolygonCollection owned by storage.
 */
[[nodiscard]] static StoredPolygonCollection safe_union(storage_handle *storage, const PolygonCollection &first, const PolygonCollection &second)
{
    // unionPolygons can slowly remove Polygons under certain circumstances, because of rounding issues (Polygons that have a thin area).
    // This does not cause a problem when actually using it on large areas, but as influence areas (representing centerpoints) can be very thin, this does occur so this ugly workaround is needed
    // Here is an example of a Polygons object that will loose vertices when unioning, and will be gone after a few times unionPolygons was called:
    /*
    Polygons example;
    Polygon exampleInner;
    exampleInner.add(Point(120410,83599));//A
    exampleInner.add(Point(120384,83643));//B
    exampleInner.add(Point(120399,83618));//C
    exampleInner.add(Point(120414,83591));//D
    exampleInner.add(Point(120423,83570));//E
    exampleInner.add(Point(120419,83580));//F
    example.add(exampleInner);
    for(int i=0;i<10;i++){
         log("Iteration %d Example area: %f\n",i,area(example));
         example=example.unionPolygons();
    }
*/

    StoredPolygonCollection result(storage);
    if (! first.empty() || ! second.empty()) {
        result = polygons_union(storage, first, second);
        if (result.empty()) {
            BOOST_LOG_TRIVIAL(debug) << "Caught an area destroying union, enlarging areas a bit.";
            // just take the few lines we have, and offset them a tiny bit. Needs to be offsetPolylines, as offset may aleady have problems with the area.
            const StoredPolylineCollection first_lines = to_polylines(storage, first);
            const StoredPolylineCollection second_lines = to_polylines(storage, second);
            result = slic3r_api::clipper_union2(
                slic3r_api::clipper_offset_polylines(storage, first_lines, scale_d(0.002), CLIPPER_JOIN_MITER, 1.2),
                slic3r_api::clipper_offset_polylines(storage, second_lines, scale_d(0.002), CLIPPER_JOIN_MITER, 1.2)).to_polygon_collection();
        }
    }

    return result;
}

[[nodiscard]] static StoredPolygonCollection safe_union(storage_handle *storage, const PolygonCollection &first)
{
    const StoredPolygonCollection nothing(storage);
    return safe_union(storage, first, nothing);
}

static bool has_rings(const StoredPolygonCollection &collection)
{
    return collection.valid() && ! collection.empty();
}

static StoredPolygonCollection safe_free_area(storage_handle *storage, const PolygonCollection &area, const PolygonCollection &forbidden)
{
    const StoredPolygonCollection free_area = diff_clipped(storage, area, forbidden);
    return safe_union(storage, free_area);
}

// The candidate influence areas of one element of a layer, all allocated in the scratch storage of create_layer_pathing().
// The collections are valid handles when the object is built and after clear(); they hold no ring when the element does not have that
// kind of area. They are no more valid once the object was moved from (see SupportElementMerging).
struct SupportElementInfluenceAreas {
    explicit SupportElementInfluenceAreas(storage_handle *storage) : influence_areas(storage), to_bp_areas(storage), to_model_areas(storage) {}

    // All influence areas: both to build plate and model.
    StoredPolygonCollection         influence_areas;
    // Influence areas just to build plate.
    StoredPolygonCollection         to_bp_areas;
    // Influence areas just to model.
    StoredPolygonCollection         to_model_areas;

    void clear() {
        this->influence_areas.clear();
        this->to_bp_areas.clear();
        this->to_model_areas.clear();
    }
};

// An element of the layer being merged. The merge moves and compacts the elements inside their vector: the collections follow the
// element (a move transfers the handle, the polygons stay where they are; the handles all belong to the layer storage), and a
// moved-from element holds no handle (has_rings() is false). The polygons of a collection are replaced by polygons_move()
// (StoredPolygonCollection::move_from()), which keeps the handle of the target.
struct SupportElementMerging {
    SupportElementMerging(storage_handle *storage, const SupportElementState &state, const SupportElement::ParentIndices &parents) :
        state(state), parents(parents), areas(storage) {}

    SupportElementState                     state;
    /*!
     * \brief All elements in the layer above the current one that are supported by this element
     */
    SupportElement::ParentIndices           parents;

    SupportElementInfluenceAreas            areas;
    // Bounding box of all influence areas.
    Eigen::AlignedBox<coord_t, 2>           bbox_data;

    const Eigen::AlignedBox<coord_t, 2>&    bbox() const { return bbox_data;}
    // The box the spatial order of the merge works on.
    c_bounding_box                          box() const
        { return c_bounding_box{ c_point{ bbox_data.min().x(), bbox_data.min().y() }, c_point{ bbox_data.max().x(), bbox_data.max().y() } }; }
    void                                    set_bbox(const c_bounding_box &abbox)
        { const coord_t eps = coord_t(SCALED_EPSILON); bbox_data = { BoxVector{ abbox.min.x - eps, abbox.min.y - eps }, BoxVector{ abbox.max.x + eps, abbox.max.y + eps } }; }
};

/*!
 * \brief Propagates influence downwards, and merges overlapping ones.
 *
 * The merging data of the layers (SupportElementMerging) is allocated in one scratch storage for the whole function: the jobs of
 * a layer fill it and the merge reads it, so it must outlive each job, and its handles are freed with the vector of each layer.
 * The influence areas that are kept are moved into new collections of the run storage.
 *
 * \param move_bounds[in,out] All currently existing influence areas
 * \param run_storage[in] The storage that owns the influence areas of the elements
 */
static void create_layer_pathing(const TreeVolumes &volumes, const TreeSettings &config, std::vector<SupportElements> &move_bounds,
                                 storage_handle *run_storage, const plugin_run_context *context)
{
    // layer_storage holds the merging data of the layer being treated.
    with_scratch_storage([&](storage_handle *layer_storage) {
        std::chrono::nanoseconds dur_inc   = std::chrono::duration_values<std::chrono::nanoseconds>::zero();
        std::chrono::nanoseconds dur_total = std::chrono::duration_values<std::chrono::nanoseconds>::zero();

        // The influence areas are merged on every layer: merging after skipped layers would move the branches farther than the branch angle
        // allows in one layer. The native tree support does the same: its cadence limit (Cura's constants in micrometres, compared with
        // coordinates scaled 1e6 per mm) evaluates to zero. Spacing the merges gave no measurable time gain; the hidden benchmark
        // [tree-routing-benchmark] (test_support_tree_family.cpp) measures a cadence.
        // Calculate the influence areas for each layer below (Top down)
        // This is done by first increasing the influence area by the allowed movement distance, and merging them with other influence areas if possible
        for (int layer_idx = int(move_bounds.size()) - 1; layer_idx > 0; -- layer_idx)
            if (SupportElements &prev_layer = move_bounds[layer_idx]; ! prev_layer.empty()) {
                const std::chrono::high_resolution_clock::time_point ta = std::chrono::high_resolution_clock::now();

                // ### Increase the influence areas by the allowed movement distance
                std::vector<SupportElementMerging> influence_areas;
                influence_areas.reserve(prev_layer.size());
                for (int32_t element_idx = 0; element_idx < int32_t(prev_layer.size()); ++ element_idx) {
                    SupportElement &el = prev_layer[element_idx];
                    assert(!el.influence_area.empty());
                    SupportElement::ParentIndices parents;
                    parents.emplace_back(element_idx);
                    influence_areas.emplace_back(layer_storage, el.state, parents);
                }
                increase_areas_one_layer(volumes, config, influence_areas, layer_idx, prev_layer, context);

                // Place already fully constructed elements to the output, remove them from influence_areas.
                SupportElements &this_layer = move_bounds[layer_idx - 1];
                influence_areas.erase(std::remove_if(influence_areas.begin(), influence_areas.end(),
                    [&this_layer, layer_idx, run_storage](SupportElementMerging &elem) {
                        if (! has_rings(elem.areas.influence_areas))
                            // This area was removed completely due to collisions.
                            return true;
                        if (! has_rings(elem.areas.to_bp_areas) && ! has_rings(elem.areas.to_model_areas)) {
                            if (polygons_area(elem.areas.influence_areas) < tiny_area_threshold) {
                                BOOST_LOG_TRIVIAL(error) << "Insert Error of Influence area bypass on layer " << layer_idx - 1;
                                BOOST_LOG_TRIVIAL(error) << "Insert error of area after bypassing merge.\n"sv;
                            }
                            // Move the area to output, in the run storage.
                            this_layer.emplace_back(elem.state, std::move(elem.parents), moved_to_storage(run_storage, elem.areas.influence_areas));
                            return true;
                        }
                        // Keep the area.
                        return false;
                    }),
                    influence_areas.end());

                dur_inc += std::chrono::high_resolution_clock::now() - ta;
                if (influence_areas.size() > 1) {
                    // ### Calculate which influence areas overlap, and merge them into a new influence area (simplified: an intersection of influence areas that have such an intersection)
                    merge_influence_areas(volumes, config, layer_idx, influence_areas, context);
                }

                dur_total += std::chrono::high_resolution_clock::now() - ta;

                // Save calculated elements to output, in the run storage, as they will not be changed again.
                for (SupportElementMerging &elem : influence_areas)
                    if (has_rings(elem.areas.influence_areas)) {
                        StoredPolygonCollection new_area = safe_union(layer_storage, elem.areas.influence_areas);
                        if (polygons_area(new_area) < tiny_area_threshold) {
                            BOOST_LOG_TRIVIAL(error) << "Insert Error of Influence area on layer " << layer_idx - 1 << ". Origin of " << elem.parents.size() << " areas. Was to bp " << elem.state.to_buildplate;
                            BOOST_LOG_TRIVIAL(error) << "Insert error of area after merge.\n"sv;
                        }
                        this_layer.emplace_back(elem.state, std::move(elem.parents), moved_to_storage(run_storage, new_area));
                    }

                slic3r_api::throw_if_cancelled(context);
            }

        BOOST_LOG_TRIVIAL(info) << "Time spent with creating influence areas' subtasks: Increasing areas " << dur_inc.count() / 1000000 <<
            " ms merging areas: " << (dur_total - dur_inc).count() / 1000000 << " ms";
    });
}

/*!
 * \brief Merges the influence areas of one layer that overlap.
 *
 * Branches which do overlap have to be merged. The elements are put in a spatial order (like the leaves of an AABB tree, so that
 * close ones are neighbours), cut in buckets, and the buckets are merged by divide and conquer: first the elements inside each
 * bucket, then pairs of buckets until one is left. Each merge job of a bucket (or of a pair) runs in parallel with its own scratch
 * storage for its temporaries. This parallelization can at most accelerate the merging by a factor of 2.
 *
 * Effects on influence_areas: the elements are reordered, merged and compacted in place. The vector keeps its size. An element
 * that was merged into another one is left cleared (valid, no ring, no parent); an element that was overwritten by the compaction is
 * moved-from (no handle); the surviving elements hold the merged areas (in their collections of the layer storage), the union of
 * the parents, the merged state and the updated box. Test the elements with has_rings() before using their areas.
 *
 * Cancellation: the context is checked once after the ordering and by the API before each merge job; a cancellation throws
 * PluginCancelled and leaves influence_areas in an unspecified but destructible state.
 *
 * \param layer_idx[in] The layer of the elements whose areas are merged (the areas are the ones of the layer below).
 * \param influence_areas[in,out] The elements of the layer, each with its three candidate areas.
 */
static void merge_influence_areas(
    const TreeVolumes                  &volumes,
    const TreeSettings                 &config,
    const LayerIndex                    layer_idx,
    std::vector<SupportElementMerging> &influence_areas,
    const plugin_run_context           *context)
{
    const size_t input_size = influence_areas.size();
    if (input_size == 0)
        return;

    // Merging by divide & conquer.
    // The majority of time is consumed by Clipper polygon operations, intersection is accelerated by bounding boxes.
    // Ordering the input like the leaves of an AABB tree helps to perform most of the intersections at first iterations,
    // thus reducing computation when merging larger subtrees.
    // The actual merge logic is found in merge_influence_areas_two_sets.

    // Sort influence_areas in place, in the order the AABB tree builder gives to its input (the tree itself is not needed).
    spatial_order(influence_areas, [](const SupportElementMerging &element) { return element.box(); });

    slic3r_api::throw_if_cancelled(context);

    // Prepare the initial buckets as ranges of influence areas. The initial buckets contain power of 2 influence areas to follow
    // the branching of the AABB tree.
    // Vectors of ranges of influence areas, following the branching of the AABB tree:
    std::vector<std::pair<SupportElementMerging*, SupportElementMerging*>> buckets;
    // Initial number of buckets for 1st round of merging.
    size_t num_buckets_initial;
    {
        // How many buckets per first merge iteration?
        // FIXME(perf): the bucket count follows the concurrency of the arena, so the merge order (hence the result) depends on the
        // number of threads, as in the legacy code; the API gives no equivalent of the arena size and the grouping is kept as it was.
        // To revisit with real performance tests.
        const size_t num_threads     = tbb::this_task_arena::max_concurrency();
        // 4 buckets per thread if possible,
        const size_t num_buckets_min = (input_size + 2) / 4;
        // 2 buckets per thread otherwise.
        const size_t num_buckets_max = input_size / 2;
        num_buckets_initial          = num_buckets_min >= num_threads ? num_buckets_min : num_buckets_max;
        const size_t bucket_size     = num_buckets_min >= num_threads ? 4 : 2;
        // Fill in the buckets.
        SupportElementMerging *it = influence_areas.data();
        // Reserve one more bucket to keep a single influence area which will not be merged in the first iteration.
        buckets.reserve(num_buckets_initial + 1);
        for (size_t i = 0; i < num_buckets_initial; ++ i, it += bucket_size)
            buckets.emplace_back(std::make_pair(it, it + bucket_size));
        SupportElementMerging *it_end = influence_areas.data() + influence_areas.size();
        if (buckets.back().second >= it_end) {
            // Last bucket is less than size 4, but bigger than size 1.
            buckets.back().second = std::min(buckets.back().second, it_end);
        } else {
            // Last bucket is size 1, it will not be merged in the first iteration.
            assert(it + 1 == it_end);
            buckets.emplace_back(std::make_pair(it, it_end));
        }
    }

    // 1st merge iteration, merge one with each other. A bucket is one job with a scratch storage of its own, shared by all the merges
    // of the bucket (the temporaries of a merge are freed when it ends); the cancellation is checked before each job.
    slic3r_api::parallel_for_storage_with_progress(0, uint32_t(num_buckets_initial), context, nullptr,
        [&](uint32_t idx, storage_handle *scratch) {
            // Merge bucket_count adjacent to each other, merging uneven bucket numbers into even buckets
            buckets[idx].second = merge_influence_areas_leaves(volumes, config, layer_idx, scratch, buckets[idx].first, buckets[idx].second);
        });

    // Further merge iterations, merging one AABB subtree with another one, hopefully minimizing intersections between the elements
    // of each of the subtree.
    while (buckets.size() > 1) {
        slic3r_api::parallel_for_storage_with_progress(0, uint32_t(buckets.size() / 2), context, nullptr,
            [&](uint32_t idx, storage_handle *scratch) {
                const size_t bucket_pair_idx = size_t(idx) * 2;
                // Merge bucket_count adjacent to each other, merging uneven bucket numbers into even buckets
                buckets[bucket_pair_idx].second = merge_influence_areas_two_sets(volumes, config, layer_idx, scratch,
                    buckets[bucket_pair_idx].first, buckets[bucket_pair_idx].second,
                    buckets[bucket_pair_idx + 1].first, buckets[bucket_pair_idx + 1].second);
            });
        // Remove odd buckets, which were merged into even buckets.
        size_t new_size = (buckets.size() + 1) / 2;
        for (size_t i = 1; i < new_size; ++ i)
            buckets[i] = std::move(buckets[i * 2]);
        buckets.erase(buckets.begin() + new_size, buckets.end());
    }
}

/*!
 * \brief Merges the range [src_begin, src_end) into the range [dst_begin, dst_end), which it follows in memory.
 *
 * The elements of a range are not merged with each other (their ranges are already merged). Each source element is merged with the
 * first destination element it overlaps, then that destination element is merged with the other destination elements it now overlaps.
 *
 * \return The end of the merged range, which starts at dst_begin: the destination survivors, then the source elements that were not
 * merged. The slots from the returned pointer to src_end hold cleared or moved-from elements. scratch holds the temporaries.
 */
static SupportElementMerging* merge_influence_areas_two_sets(
    const TreeVolumes &volumes, const TreeSettings &config, const LayerIndex layer_idx, storage_handle *scratch,
    SupportElementMerging * const dst_begin, SupportElementMerging *       dst_end,
    SupportElementMerging *       src_begin, SupportElementMerging * const src_end)
{
    // Merging src into dst.
    // Areas of src should not overlap with areas of another elements of src.
    // Areas of dst should not overlap with areas of another elements of dst.
    // The memory from dst_begin to src_end is reserved for the merging operation,
    // src follows dst.
    assert(src_begin < src_end);
    assert(dst_begin < dst_end);
    assert(dst_end <= src_begin);
    for (SupportElementMerging *src = src_begin; src != src_end; ++ src) {
        SupportElementMerging         *dst      = dst_begin;
        SupportElementMerging         *merged   = nullptr;
        for (; dst != dst_end; ++ dst)
            if (merge_influence_areas_two_elements(volumes, config, layer_idx, scratch, *dst, *src)) {
                merged = dst ++;
                if (src != src_begin)
                    // Compactify src.
                    *src = std::move(*src_begin);
                ++ src_begin;
                break;
            }
        for (; dst != dst_end;)
            if (merge_influence_areas_two_elements(volumes, config, layer_idx, scratch, *merged, *dst)) {
                // Compactify dst.
                if (dst != -- dst_end)
                    *dst = std::move(*dst_end);
            } else
                ++ dst;
    }
    // Compactify src elements that were not merged with dst to the end of dst.
    assert(dst_end <= src_begin);
    if (dst_end == src_begin)
        dst_end = src_end;
    else
        while (src_begin != src_end)
            *dst_end ++ = std::move(*src_begin ++);

    return dst_end;
}

/*!
 * \brief Merges the elements of the range [dst_begin, dst_end) with each other, one against the others (O(n^2)).
 *
 * When an element is merged into another one, the last element of the range takes its place (it is moved, with its collections).
 *
 * \return The new end of the range: [dst_begin, end) holds the survivors, with their merged areas, states and parents; the slots after
 * it hold moved-from elements. scratch holds the temporaries of the merges.
 */
static SupportElementMerging* merge_influence_areas_leaves(
    const TreeVolumes &volumes, const TreeSettings &config, const LayerIndex layer_idx, storage_handle *scratch,
    SupportElementMerging * const dst_begin, SupportElementMerging *dst_end)
{
    // Merging at the lowest level of the AABB tree. Checking one against each other, O(n^2).
    assert(dst_begin < dst_end);
    for (SupportElementMerging *i = dst_begin; i + 1 < dst_end;) {
        for (SupportElementMerging *j = i + 1; j != dst_end;)
            if (merge_influence_areas_two_elements(volumes, config, layer_idx, scratch, *i, *j)) {
                // i was merged with j, j is empty.
                if (j != -- dst_end)
                    *j = std::move(*dst_end);
                goto merged;
            } else
                ++ j;
        // not merged
        ++ i;
    merged:
        ;
    }
    return dst_end;
}

/*!
 * \brief Merges src into dst when their areas overlap enough and their states allow it.
 *
 * The test works on the bounding boxes first, then on the common part of the areas (the smaller one grown by the radius difference,
 * up to the collision). The common part is computed in scratch; nothing is kept there.
 *
 * \return false when the elements do not merge: both are untouched. true when they merge: dst takes the merged state, the parents of
 * both, the new areas (the polygons move into its collections) and the box that holds them; src is cleared (valid, no ring, no parent).
 */
static bool merge_influence_areas_two_elements(
    const TreeVolumes &volumes, const TreeSettings &config, const LayerIndex layer_idx, storage_handle *scratch,
    SupportElementMerging &dst, SupportElementMerging &src)
{
    // Don't merge gracious with a non gracious area as bad placement could negatively impact reliability of the whole subtree.
    const bool merging_gracious_and_non_gracious = dst.state.to_model_gracious != src.state.to_model_gracious;
    // Could cause some issues with the increase of one area, as it is assumed that if the smaller is increased
    // by the delta to the larger it is engulfed by it already. But because a different collision
    // may be removed from the in draw_area() generated circles, this assumption could be wrong.
    const bool merging_min_and_regular_xy        = dst.state.use_min_xy_dist != src.state.use_min_xy_dist;

    if (merging_gracious_and_non_gracious || merging_min_and_regular_xy)
        return false;

    const bool dst_radius_bigger = support_element_collision_radius(config, dst.state) > support_element_collision_radius(config, src.state);
    const SupportElementMerging &smaller_rad = dst_radius_bigger ? src : dst;
    const SupportElementMerging &bigger_rad  = dst_radius_bigger ? dst : src;
    const coord_t real_radius_delta = std::abs(support_element_radius(config, bigger_rad.state) - support_element_radius(config, smaller_rad.state));
    {
        // Testing intersection of bounding boxes.
        // Expand the smaller radius branch bounding box to match the lambda intersect_small_with_bigger() below.
        // Because the lambda intersect_small_with_bigger() applies a rounded offset, a snug offset of the bounding box
        // is sufficient. On the other side, if a mitered offset was used by the lambda,
        // the bounding box expansion would have to account for the mitered extension of the sharp corners.
        Eigen::AlignedBox<coord_t, 2> smaller_bbox = smaller_rad.bbox();
        smaller_bbox.min() -= BoxVector{ real_radius_delta, real_radius_delta };
        smaller_bbox.max() += BoxVector{ real_radius_delta, real_radius_delta };
        if (! smaller_bbox.intersects(bigger_rad.bbox()))
            return false;
    }

    // Accumulator of a radius increase of a "to model" branch by merging in a "to build plate" branch.
    coord_t increased_to_model_radius = 0;
    const bool merging_to_bp                     = dst.state.to_buildplate && src.state.to_buildplate;
    if (! merging_to_bp) {
        // Get the real radius increase as the user does not care for the collision model.
        if (dst.state.to_buildplate != src.state.to_buildplate) {
            // Merging a "to build plate" branch with a "to model" branch.
            // Don't allow merging a thick "to build plate" branch into a thinner "to model" branch.
            const coord_t rdst = support_element_radius(config, dst.state);
            const coord_t rsrc = support_element_radius(config, src.state);
            if (dst.state.to_buildplate) {
                if (rsrc < rdst)
                    increased_to_model_radius = src.state.increased_to_model_radius + rdst - rsrc;
            } else {
                if (rsrc > rdst)
                    increased_to_model_radius = dst.state.increased_to_model_radius + rsrc - rdst;
            }
            if (increased_to_model_radius > config.max_to_model_radius_increase)
                return false;
        }
        // if a merge could place a stable branch on unstable ground, would be increasing the radius further
        // than allowed to when merging to model and to_bp trees or would merge to model before it is known
        // they will even been drawn the merge is skipped
        // Both states were propagated down to the same layer; the higher tip of the two decides the height above the model.
        assert(src.state.layer_idx == dst.state.layer_idx);
        if (! config.reaches_min_height_to_model(dst.state.layer_idx, std::max(src.state.distance_to_top, dst.state.distance_to_top)))
            return false;
    }

    // Area of the bigger radius is used to ensure correct placement regarding the relevant avoidance,
    // so if that would change an invalid area may be created.
    if (! bigger_rad.state.can_use_safe_radius && smaller_rad.state.can_use_safe_radius)
        return false;

    // the bigger radius is used to verify that the area is still valid after the increase with the delta.
    // If there were a point where the big influence area could be valid with can_use_safe_radius
    // the element would already be can_use_safe_radius.
    // the smaller radius, which gets increased by delta may reach into the area where use_min_xy_dist is no longer required.
    const bool use_min_radius = bigger_rad.state.use_min_xy_dist && smaller_rad.state.use_min_xy_dist;

    // The idea is that the influence area with the smaller collision radius is increased by the radius difference.
    // If this area has any intersections with the influence area of the larger collision radius, a branch (of the larger collision radius) placed in this intersection, has already engulfed the branch of the smaller collision radius.
    // Because of this a merge may happen even if the influence areas (that represent possible center points of branches) do not intersect yet.
    // Remember that collision radius <= real radius as otherwise this assumption would be false.
    const coord_t   smaller_collision_radius    = support_element_collision_radius(config, smaller_rad.state);
    const StoredPolygonCollection &collision    = volumes.getCollision(smaller_collision_radius, layer_idx - 1, use_min_radius);
    // The small area grown by the radius difference (up to the collision), common part with the bigger area. The temporaries of the
    // computation live in the scratch storage of the merge job; the result too, the caller moves it where it stays.
    auto            intersect_small_with_bigger = [real_radius_delta, smaller_collision_radius, &collision, &config, scratch](
                        const PolygonCollection &small, const PolygonCollection &bigger) {
        const StoredPolygonCollection grown = safe_offset_inc(
            scratch, small, real_radius_delta, collision,
            // -3 avoids possible rounding errors
            2 * (config.xy_distance + smaller_collision_radius - 3), 0, 0);
        return polygons_intersection(scratch, grown, bigger);
    };
//#define TREES_MERGE_RATHER_LATER
    StoredPolygonCollection intersect =
        intersect_small_with_bigger(
        merging_to_bp ? smaller_rad.areas.to_bp_areas : smaller_rad.areas.to_model_areas,
        merging_to_bp ? bigger_rad.areas.to_bp_areas : bigger_rad.areas.to_model_areas);

    // dont use empty as a line is not empty, but for this use-case it very well may be (and would be one layer down as union does not keep lines)
    // check if the overlap is large enough (Small ares tend to attract rounding errors in clipper).
    if (polygons_area(intersect) <= tiny_area_threshold)
        return false;

    // While 0.025 was guessed as enough, i did not have reason to change it.
    // The area is shrunk: it is the output of an intersection, a clean region (see polygons_offset()).
    {
        const StoredPolygonCollection shrunk = polygons_offset(scratch, intersect, scale_d(-0.025), CLIPPER_JOIN_MITER, 1.2);
        if (polygons_area(shrunk) <= tiny_area_threshold)
            return false;
    }


    // Do the actual merge now that the branches are confirmed to be able to intersect.
    // calculate which point is closest to the point of the last merge (or tip center if no merge above it has happened)
    // used at the end to estimate where to best place the branch on the bottom most layer
    // could be replaced with a random point inside the new area
    const c_point new_pos = move_inside_if_outside(intersect, dst.state.next_position);

    SupportElementState new_state = merge_support_element_states(dst.state, src.state, new_pos, layer_idx - 1, config);
    // The areas of both parents were validated with their own collision radii. If the merged state needs a larger ceiled radius
    // than both (its foot carries the drawn radius of the larger parent), those areas do not hold for it: refuse the merge, before
    // dst or src are modified.
    if (merge_crosses_cache_step(volumes.ceilRadius(support_element_collision_radius(config, new_state), use_min_radius),
                                 volumes.ceilRadius(support_element_collision_radius(config, dst.state), use_min_radius),
                                 volumes.ceilRadius(support_element_collision_radius(config, src.state), use_min_radius)))
        return false;
    new_state.increased_to_model_radius = increased_to_model_radius == 0 ?
        // increased_to_model_radius was not set yet. Propagate maximum.
        std::max(dst.state.increased_to_model_radius, src.state.increased_to_model_radius) :
        increased_to_model_radius;

    // Rather unioning with "intersect" due to some rounding errors.
    const StoredPolygonCollection small_in_bigger = intersect_small_with_bigger(smaller_rad.areas.influence_areas, bigger_rad.areas.influence_areas);
    StoredPolygonCollection influence_areas = safe_union(scratch, small_in_bigger, intersect);

    StoredPolygonCollection to_model_areas(scratch);
    if (merging_to_bp && config.support_rests_on_model) {
        if (new_state.to_model_gracious) {
            // Rather unioning with "intersect" due to some rounding errors.
            const StoredPolygonCollection model_small_in_bigger = intersect_small_with_bigger(smaller_rad.areas.to_model_areas, bigger_rad.areas.to_model_areas);
            to_model_areas = safe_union(scratch, model_small_in_bigger, intersect);
        } else
            to_model_areas.copy_from(influence_areas);
    }

    // The results move into the collections of dst, which belong to the storage of the layer.
    dst.parents.insert(dst.parents.end(), src.parents.begin(), src.parents.end());
    dst.state = new_state;
    dst.areas.influence_areas.move_from(influence_areas);
    dst.areas.to_bp_areas.clear();
    dst.areas.to_model_areas.clear();
    if (merging_to_bp) {
        dst.areas.to_bp_areas.move_from(intersect);
        if (config.support_rests_on_model)
            dst.areas.to_model_areas.move_from(to_model_areas);
    } else
        dst.areas.to_model_areas.move_from(intersect);
    // Update the bounding box.
    c_bounding_box bbox = polygons_bounding_box(dst.areas.influence_areas);
    slic3r_api::bounding_box_merge(bbox, polygons_bounding_box(dst.areas.to_bp_areas));
    slic3r_api::bounding_box_merge(bbox, polygons_bounding_box(dst.areas.to_model_areas));
    dst.set_bbox(bbox);
    // Clear the source data.
    src.areas.clear();
    src.parents.clear();
    return true;
}

/*!
 * \brief Increases influence areas as far as required.
 *
 * Calculates influence areas of the layer below, based on the influence areas of the current layer.
 * Increases every influence area by maximum_move_distance_slow. If this is not enough, as in it would change the gracious or to_buildplate status, the influence areas are instead increased by maximum_move_distance.
 * Also ensures that increasing the radius of a branch, does not cause it to change its status (like to_buildplate ). If this were the case, the radius is not increased instead.
 *
 * One parallel task per element, each with a scratch storage of its own for its temporaries (see increase_merging_area()). The tasks
 * share nothing mutable: a task writes its own merging area and the state of its own parent.
 *
 * Effects: for every merging area, the state of the element on the layer below, the three candidate areas (the polygons move into the
 * collections of the merging area, in the layer storage) and the box that holds them. An element that cannot be increased leaves its
 * merging area without ring, and its parent in layer_elements is marked lost (no result point, not gracious, verylost).
 *
 * Cancellation: checked at the end of each task; a cancellation throws PluginCancelled.
 *
 * \param merging_areas[in,out] One per element of layer_elements (merging_areas[i] has the single parent i), created with the state of
 * the parent and empty areas.
 * \param layer_idx[in] Number of the layer of layer_elements, the layer above the one that is computed.
 * \param layer_elements[in,out] The elements of the layer above; their influence areas are read, their states may be marked lost.
 */
static void increase_areas_one_layer(
    const TreeVolumes                  &volumes,
    const TreeSettings                 &config,
    // New areas at the layer below layer_idx
    std::vector<SupportElementMerging> &merging_areas,
    // Layer above merging_areas.
    const LayerIndex                    layer_idx,
    // Layer elements above merging_areas.
    SupportElements                    &layer_elements,
    const plugin_run_context           *context)
{
    // FIXME(perf): one task per element (grain 1, simple_partitioner) as the legacy loop: the cost of an element varies a lot (a
    // few offsets or dozens), so no grouping is wanted, and slic3r_parallel_for_storage() gives no control of it. Each task takes a
    // scratch storage of its own (with_scratch_storage(), a nested job of one index run inline). To revisit with real performance
    // tests, with slic3r_parallel_for_storage() and the scratch storage of its jobs.
    tbb::parallel_for(tbb::blocked_range<size_t>(0, merging_areas.size(), 1),
        [&](const tbb::blocked_range<size_t> &range) {
        for (size_t merging_area_idx = range.begin(); merging_area_idx < range.end(); ++ merging_area_idx)
            with_scratch_storage([&](storage_handle *scratch) {
                increase_merging_area(scratch, volumes, config, merging_areas[merging_area_idx], layer_idx, layer_elements, context);
            });
    }, tbb::simple_partitioner());
}

// The task of one element: its candidate influence areas on the layer below. The temporaries live in the scratch storage of the task
// (their collections are allocated when first used); the areas that are kept move into the collections of the merging element
// (storage of the layer). Writes only merging_area and the state of its own parent.
// layer_idx names a layer above the bed; settings stay unchanged, volumes may fill caches on demand, and allocation or cancellation failures propagate.
static void increase_merging_area(
    storage_handle *scratch, const TreeVolumes &volumes, const TreeSettings &config, SupportElementMerging &merging_area,
    const LayerIndex layer_idx, SupportElements &layer_elements, const plugin_run_context *context)
{
    using AvoidanceType = TreeVolumes::AvoidanceType;

    assert(merging_area.parents.size() == 1);
    SupportElement          &parent         = layer_elements[merging_area.parents.front()];
    SupportElementState      elem           = SupportElementState::propagate_down(parent.state);
    const StoredPolygonCollection &wall_restriction =
        // Abstract representation of the model outline. If an influence area would move through it, it could teleport through a wall.
        volumes.getWallRestriction(support_element_collision_radius(config, parent.state), layer_idx, parent.state.use_min_xy_dist);


    LazyPolygons to_bp_data(scratch), to_model_data(scratch);
    coord_t radius = support_element_collision_radius(config, elem);

    // When the radius increases, the outer "support wall" of the branch will have been moved farther away from the center (as this is the definition of radius).
    // As it is not specified that the support_tree_angle has to be one of the center of the branch, it is here seen as the smaller angle of the outer wall of the branch, to the outer wall of the same branch one layer above.
    // As the branch may have become larger the distance between these 2 walls is smaller than the distance of the center points.
    // These extra distance is added to the movement distance possible for this layer.

    coord_t extra_speed = 5; // The extra speed is added to both movement distances. Also move 5 scaled units (5 nm) faster than allowed to avoid rounding errors, this may cause issues at VERY VERY small layer heights.
    coord_t extra_slow_speed = 0; // Only added to the slow movement distance.
    const coord_t ceiled_parent_radius = volumes.ceilRadius(support_element_collision_radius(config, parent.state), parent.state.use_min_xy_dist);
    // The gain of the branch after the step it is attempting (layer_idx to layer_idx - 1): elem only propagates the state of the
    // parent, so its gain is the parent's.
    const double projected_gain = config.advance(parent.state.radius_gain, layer_idx);
    coord_t projected_radius_increased = radius_from_gain(config, projected_gain, parent.state.foot_gain);
    coord_t projected_radius_delta = projected_radius_increased - support_element_collision_radius(config, parent.state);

    // When both gap windows contain their neighbouring layers, the collision used for wall restriction includes their walls
    // (not just xy_min_distance), as shown below (d = blocked area because of the Z gap):
    /*
     *  layer z+1:dddddiiiiiioooo
     *  layer z+0:xxxxxdddddddddd
     *  layer z-1:dddddxxxxxxxxxx
     *  For more detailed visualisation see calculateWallRestrictions
     */
    const coord_t safe_movement_distance =
        (elem.use_min_xy_dist ? config.xy_min_distance : config.xy_distance) +
        (config.z_distance_both_sides ? config.min_feature_size : 0);
    if (ceiled_parent_radius == volumes.ceilRadius(projected_radius_increased, parent.state.use_min_xy_dist) ||
        projected_radius_increased < config.increase_radius_until_radius)
        // If it is guaranteed possible to increase the radius, the maximum movement speed can be increased, as it is assumed that the maximum movement speed is the one of the slower moving wall
        extra_speed += projected_radius_delta;
    else
        // if a guaranteed radius increase is not possible, only increase the slow speed
        // Ensure that the slow movement distance can not become larger than the fast one.
        extra_slow_speed += std::min(projected_radius_delta, (config.maximum_move_distance(layer_idx) + extra_speed) - (config.maximum_move_distance_slow(layer_idx) + extra_slow_speed));

    // The foot adds no lateral speed: the chosen setting may not grow the radius.

    const coord_t fast_speed = config.maximum_move_distance(layer_idx) + extra_speed;
    const coord_t slow_speed = config.maximum_move_distance_slow(layer_idx) + extra_speed + extra_slow_speed;

    LazyPolygons offset_slow(scratch), offset_fast(scratch);

    bool add = false;
    bool bypass_merge = false;
    constexpr bool increase_radius = true, no_error = true, use_min_radius = true, move = true; // aliases for better readability

    // Determine in which order configurations are checked if they result in a valid influence area. Check will stop if a valid area is found
    std::vector<AreaIncreaseSettings> order;
    auto insertSetting = [&](AreaIncreaseSettings settings, bool back) {
        if (std::find(order.begin(), order.end(), settings) == order.end()) {
            if (back)
                order.emplace_back(settings);
            else
                order.insert(order.begin(), settings);
        }
    };

    const bool parent_moved_slow = elem.last_area_increase.increase_speed < config.maximum_move_distance(layer_idx);
    const bool avoidance_speed_mismatch = parent_moved_slow && elem.last_area_increase.type != AvoidanceType::Slow;
    // branch may still go though a hole, so a check has to be done whether the hole was already passed, and the regular avoidance can be used.
    if (!elem.can_use_safe_radius) {
        // if the radius until which it is always increased can not be guaranteed, move fast. This is to avoid holes smaller than the real branch radius.
        // This does not guarantee the avoidance of such holes, but ensures they are avoided if possible.
        // order.emplace_back(AvoidanceType::Slow,!increase_radius,no_error,!use_min_radius,move);
        insertSetting({ AvoidanceType::Slow, slow_speed, increase_radius, no_error, !use_min_radius, !move }, true); // did we go through the hole
        // in many cases the definition of hole is overly restrictive, so to avoid unnecessary fast movement in the tip, it is ignored there for a bit.
        // This CAN cause a branch to go though a hole it otherwise may have avoided.
        if (config.path_gain(elem.layer_idx, elem.distance_to_top) < 0.5 * config.tip_total_gain)
            insertSetting({ AvoidanceType::Fast, slow_speed, increase_radius, no_error, !use_min_radius, !move }, true);
        insertSetting({ AvoidanceType::FastSafe, fast_speed, increase_radius, no_error, !use_min_radius, !move }, true); // did we manage to avoid the hole
        insertSetting({ AvoidanceType::FastSafe, fast_speed, !increase_radius, no_error, !use_min_radius, move }, true);
        insertSetting({ AvoidanceType::Fast, fast_speed, !increase_radius, no_error, !use_min_radius, move }, true);
    } else {
        insertSetting({ AvoidanceType::Slow, slow_speed, increase_radius, no_error, !use_min_radius, move }, true);
        // while moving fast to be able to increase the radius (b) may seems preferable (over a) this can cause the a sudden skip in movement,
        // which looks similar to a layer shift and can reduce stability.
        // as such idx have chosen to only use the user setting for radius increases as a friendly recommendation.
        insertSetting({ AvoidanceType::Slow, slow_speed, !increase_radius, no_error, !use_min_radius, move }, true); // a
        if (config.path_gain(elem.layer_idx, elem.distance_to_top) < config.tip_total_gain)
            insertSetting({ AvoidanceType::FastSafe, slow_speed, increase_radius, no_error, !use_min_radius, move }, true);
        insertSetting({ AvoidanceType::FastSafe, fast_speed, increase_radius, no_error, !use_min_radius, move }, true); // b
        insertSetting({ AvoidanceType::FastSafe, fast_speed, !increase_radius, no_error, !use_min_radius, move }, true);
    }

    if (elem.use_min_xy_dist) {
        std::vector<AreaIncreaseSettings> new_order;
        // if the branch currently has to use min_xy_dist check if the configuration would also be valid
        // with the regular xy_distance before checking with use_min_radius (Only happens when Support Distance priority is z overrides xy )
        for (AreaIncreaseSettings settings : order) {
            new_order.emplace_back(settings);
            new_order.push_back({ settings.type, settings.increase_speed, settings.increase_radius, settings.no_error, use_min_radius, settings.move });
        }
        order = new_order;
    }
    if (elem.to_buildplate || (elem.to_model_gracious && polygons_intersection(scratch, parent.influence_area, volumes.getPlaceableAreas(radius, layer_idx)).empty())) {
        // error case
        // it is normal that we wont be able to find a new area at some point in time if we wont be able to reach layer 0 aka have to connect with the model
        insertSetting({ AvoidanceType::Fast, fast_speed, !increase_radius, !no_error, elem.use_min_xy_dist, move }, true);
    }

    StoredPolygonCollection inc_wo_collision(scratch);
    // Check whether it is faster to calculate the area increased with the fast speed independently from the slow area, or time could be saved by reusing the slow area to calculate the fast one.
    // Calculated by comparing the steps saved when calcualting idependently with the saved steps when not.
    bool offset_independant_faster = radius / safe_movement_distance - int(config.maximum_move_distance(layer_idx) + extra_speed < radius + safe_movement_distance) >
                                     round_up_divide((extra_speed + extra_slow_speed + config.maximum_move_distance_slow(layer_idx)), safe_movement_distance);
    for (const AreaIncreaseSettings &settings : order) {
        if (settings.move) {
            if (offset_slow.empty() && (settings.increase_speed == slow_speed || ! offset_independant_faster)) {
                // offsetting in 2 steps makes our offsetted area rounder preventing (rounding) errors created by to pointy areas.
                offset_slow.get() = safe_offset_inc(scratch, parent.influence_area, extra_speed + extra_slow_speed + config.maximum_move_distance_slow(layer_idx),
                    wall_restriction, safe_movement_distance, offset_independant_faster ? safe_movement_distance + radius : 0, 2);
            }
            if (offset_fast.empty() && settings.increase_speed != slow_speed) {
                if (offset_independant_faster)
                    offset_fast.get() = safe_offset_inc(scratch, parent.influence_area, extra_speed + config.maximum_move_distance(layer_idx),
                        wall_restriction, safe_movement_distance, offset_independant_faster ? safe_movement_distance + radius : 0, 1);
                else {
                    const coord_t delta_slow_fast = config.maximum_move_distance(layer_idx) - (config.maximum_move_distance_slow(layer_idx) + extra_slow_speed);
                    offset_fast.get() = safe_offset_inc(scratch, offset_slow.get(), delta_slow_fast, wall_restriction, safe_movement_distance, safe_movement_distance + radius, offset_independant_faster ? 2 : 1);
                }
            }
        }
        std::optional<SupportElementState> result;
        inc_wo_collision.clear();
        if (!settings.no_error) {
            // ERROR CASE
            // if the area becomes for whatever reason something that clipper sees as a line, offset would stop working, so ensure that even if if wrongly would be a line, it still actually has an area that can be increased
            const StoredPolylineCollection area_lines = to_polylines(scratch, parent.influence_area);
            const slic3r_api::ClipperContext clipper(scratch);
            const StoredPolygonCollection base_error_area = slic3r_api::clipper_union2(clipper(parent.influence_area),
                slic3r_api::clipper_offset_polylines(scratch, area_lines, scale_d(0.005), CLIPPER_JOIN_MITER, 1.2)).to_polygon_collection();
            result = increase_single_area(scratch, volumes, config, settings, layer_idx, parent,
                base_error_area, to_bp_data, to_model_data, inc_wo_collision, (config.maximum_move_distance(layer_idx) + extra_speed) * 1.5);
            BOOST_LOG_TRIVIAL(warning)
                  << "Influence area could not be increased! Data about the Influence area: "
                     "Radius: " << radius << " at layer: " << layer_idx - 1 << " NextTarget: " << elem.layer_idx << " Distance to top: " << elem.distance_to_top <<
                     " Foot gain " << elem.foot_gain << " use_min_xy_dist " << elem.use_min_xy_dist << " to buildplate " << elem.to_buildplate <<
                     " gracious " << elem.to_model_gracious << " safe " << elem.can_use_safe_radius << " \n "
                     "Parent " << &parent << ": Radius: " << support_element_collision_radius(config, parent.state) << " at layer: " << layer_idx << " NextTarget: " << parent.state.layer_idx <<
                     " Distance to top: " << parent.state.distance_to_top << " Foot gain " << parent.state.foot_gain << "  use_min_xy_dist " << parent.state.use_min_xy_dist <<
                     " to buildplate " << parent.state.to_buildplate << " gracious " << parent.state.to_model_gracious << " safe " << parent.state.can_use_safe_radius;
            BOOST_LOG_TRIVIAL(error) << "Potentially lost branch!"sv;
            if (result)
                result->lost = true;
        } else
            result = increase_single_area(scratch, volumes, config, settings, layer_idx, parent,
                (settings.increase_speed == slow_speed ? offset_slow : offset_fast).get(), to_bp_data, to_model_data, inc_wo_collision, 0);

        if (result) {
            elem = *result;
            radius = support_element_collision_radius(config, elem);
            elem.last_area_increase = settings;
            add = true;
            // do not merge if the branch should not move or the priority has to be to get farther away from the model.
            bypass_merge = !settings.move || (settings.use_min_distance && config.path_gain(elem.layer_idx, elem.distance_to_top) < config.tip_total_gain);
            if (! settings.move)
                elem.result_on_layer = parent.state.result_on_layer;

            elem.can_use_safe_radius = settings.type != AvoidanceType::Fast;

            if (!settings.use_min_distance)
                elem.use_min_xy_dist = false;
            if (!settings.no_error)
                BOOST_LOG_TRIVIAL(info)
                    << "Trying to keep area by moving faster than intended: Success";
            break;
        } else if (!settings.no_error)
            BOOST_LOG_TRIVIAL(error) << "Trying to keep area by moving faster than intended: FAILURE! WRONG BRANCHES LIKLY!";
    }

    if (add) {
        // Union seems useless, but some rounding errors somewhere can cause to_bp_data to be slightly bigger than it should be.
        assert(! inc_wo_collision.empty() || ! to_bp_data.empty() || ! to_model_data.empty());
        const StoredPolygonCollection free_increase = diff_clipped(scratch, inc_wo_collision, volumes.getCollision(radius, layer_idx - 1, elem.use_min_xy_dist));
        const StoredPolygonCollection free_union = safe_union(scratch, to_bp_data.get(), to_model_data.get());
        StoredPolygonCollection max_influence_area = safe_union(scratch, free_increase, free_union);
        merging_area.state = elem;
        assert(!max_influence_area.empty());
        merging_area.set_bbox(polygons_bounding_box(max_influence_area));
        // The candidate areas stay in the collections of the layer: the rings move into them.
        merging_area.areas.influence_areas.move_from(max_influence_area);
        if (! bypass_merge) {
            if (elem.to_buildplate)
                merging_area.areas.to_bp_areas.move_from(to_bp_data.get());
            if (config.support_rests_on_model)
                merging_area.areas.to_model_areas.move_from(to_model_data.get());
        }
    } else {
        // If the bottom most point of a branch is set, later functions will assume that the position is valid, and ignore it.
        // But as branches connecting with the model that are to small have to be culled, the bottom most point has to be not set.
        // A point can be set on the top most tip layer (a step without move puts the parent's point for one step).
        parent.state.result_on_layer_reset();
        parent.state.to_model_gracious = false;
        parent.state.verylost = true;
    }

    // The task ends with a cancellation check; the lazy computations of the volumes check the same context.
    slic3r_api::throw_if_cancelled(context);
}

/*!
 * \brief Checks if an influence area contains a valid subsection and returns the corresponding metadata and the new Influence area.
 *
 * Calculates an influence areas of the layer below, based on the influence area of one element on the current layer.
 * Increases every influence area by maximum_move_distance_slow. If this is not enough, as in we would change our gracious or to_buildplate status the influence areas are instead increased by maximum_move_distance_slow.
 * Also ensures that increasing the radius of a branch, does not cause it to change its status (like to_buildplate ). If this were the case, the radius is not increased instead.
 *
 * The parent has a valid influence area (a stored collection): it is copied when the element does not move. All the collections written
 * here belong to the scratch storage of the task; the caller moves the ones it keeps. The function can be called again with the next
 * settings and the same output collections: a collection that a call does not fill keeps its previous content.
 * Allocation and cancellation failures propagate; no ownership of the borrowed parent or settings is transferred.
 *
 * \param scratch[in] The storage of the temporaries and of the collections that are filled.
 * \param settings[in] Which settings have to be used to check validity.
 * \param layer_idx[in] Number of the current layer.
 * \param parent[in] The element of the layer above (its state and its influence area).
 * \param relevant_offset[in] The maximal possible influence area. No guarantee regarding validity with current layer collision required, as it is ensured in-function! Only read when the element moves.
 * \param to_bp_data[out] The part of the Influence area that can reach the buildplate (allocated when it is first filled).
 * \param to_model_data[out] The part of the Influence area that do not have to reach the buildplate. This has overlap with to_bp_data.
 * \param increased[out]  Area than can reach all further up support points. No assurance is made that the buildplate or the model can be reached in accordance to the user-supplied settings. It is replaced (not appended to).
 * \param overspeed[in] How much should the already offset area be offset again. Usually this is 0.
 * \return The state of the element on the layer below (status and radius may have been corrected), or nothing if no influence area can be created using the supplied influence area and settings.
 */
[[nodiscard]] static std::optional<SupportElementState> increase_single_area(
    storage_handle                 *scratch,
    const TreeVolumes              &volumes,
    const TreeSettings             &config,
    const AreaIncreaseSettings     &settings,
    const LayerIndex                layer_idx,
    const SupportElement           &parent,
    const StoredPolygonCollection  &relevant_offset,
    LazyPolygons                   &to_bp_data,
    LazyPolygons                   &to_model_data,
    StoredPolygonCollection        &increased,
    const coord_t                   overspeed)
{
    SupportElementState current_elem{ SupportElementState::propagate_down(parent.state) };
    if (settings.increase_radius)
        current_elem.radius_gain = config.advance(current_elem.radius_gain, layer_idx);
    coord_t radius = support_element_collision_radius(config, current_elem);

    if (settings.move) {
        increased.copy_from(relevant_offset);
        if (overspeed > 0) {
            const coord_t safe_movement_distance =
                (current_elem.use_min_xy_dist ? config.xy_min_distance : config.xy_distance) +
                (config.z_distance_both_sides ? config.min_feature_size : 0);
            // The difference to ensure that the result not only conforms to wall_restriction, but collision/avoidance is done later.
            // The higher last_safe_step_movement_distance comes exactly from the fact that the collision will be subtracted later.
            StoredPolygonCollection overspeed_area = safe_offset_inc(scratch, increased, overspeed,
                volumes.getWallRestriction(support_element_collision_radius(config, parent.state), layer_idx, parent.state.use_min_xy_dist),
                safe_movement_distance, safe_movement_distance + radius, 1);
            increased.move_from(overspeed_area);
        }
    } else
        // if no movement is done the areas keep parent area as no move == offset(0)
        increased.copy_from(parent.influence_area);

    StoredPolygonCollection to_bp_area = safe_free_area(scratch, increased, volumes.getAvoidance(radius, layer_idx - 1, settings.type, false, settings.use_min_distance));
    to_bp_data.get().move_from(to_bp_area);
    if (! current_elem.to_buildplate && to_bp_data.area() > tiny_area_threshold) {
        // mostly happening in the tip, but it is checked every time, just to be sure.
        current_elem.to_buildplate = true; // sometimes nodes that can reach the buildplate are marked as cant reach, tainting subtrees. This corrects it.
        BOOST_LOG_TRIVIAL(debug) << "Corrected taint leading to a wrong to model value on layer " << layer_idx - 1 << " targeting " <<
            current_elem.target_height << " with radius " << radius;
    }
    if (config.support_rests_on_model) {
        StoredPolygonCollection to_model_area = safe_free_area(scratch, increased, volumes.getAvoidance(radius, layer_idx - 1, settings.type, true, settings.use_min_distance));
        to_model_data.get().move_from(to_model_area);

        if (!current_elem.to_model_gracious) {
            if (to_model_data.area() >= tiny_area_threshold) {
                current_elem.to_model_gracious = true;
                BOOST_LOG_TRIVIAL(debug) << "Corrected taint leading to a wrong non gracious value on layer " << layer_idx - 1 << " targeting " <<
                    current_elem.target_height << " with radius " << radius;
            } else {
                // Cannot route to gracious areas. Push the tree away from object and route it down anyways.
                StoredPolygonCollection pushed_area = safe_free_area(scratch, increased, volumes.getCollision(radius, layer_idx - 1, settings.use_min_distance));
                to_model_data.get().move_from(pushed_area);
            }
        }
    }

    // The area that decides whether the element can be increased: the one to the build plate or the one to the model (the status of the
    // element does not change below). The collections keep their handles when they are refilled, so the reference stays valid.
    const StoredPolygonCollection &check_layer_data = current_elem.to_buildplate ? to_bp_data.get() : to_model_data.get();

    if (settings.increase_radius && polygons_area(check_layer_data) > tiny_area_threshold) {
        auto validWithRadius = [&](coord_t next_radius) {
            if (volumes.ceilRadius(next_radius, settings.use_min_distance) <= volumes.ceilRadius(radius, settings.use_min_distance))
                return true;

            StoredPolygonCollection check_layer_data_2(scratch);
            if (current_elem.to_buildplate)
                // regular union as output will not be used later => this area should always be a subset of the safe_union one (i think)
                check_layer_data_2 = diff_clipped(scratch, increased, volumes.getAvoidance(next_radius, layer_idx - 1, settings.type, false, settings.use_min_distance));
            else if (config.support_rests_on_model)
                check_layer_data_2 = diff_clipped(scratch, increased,
                    current_elem.to_model_gracious ?
                        volumes.getAvoidance(next_radius, layer_idx - 1, settings.type, true, settings.use_min_distance) :
                        volumes.getCollision(next_radius, layer_idx - 1, settings.use_min_distance));
            return polygons_area(check_layer_data_2) > tiny_area_threshold;
        };
        coord_t ceil_radius_before = volumes.ceilRadius(radius, settings.use_min_distance);

        if (support_element_collision_radius(config, current_elem) < config.increase_radius_until_radius && support_element_collision_radius(config, current_elem) < support_element_radius(config, current_elem)) {
            coord_t target_radius = std::min(support_element_radius(config, current_elem), config.increase_radius_until_radius);
            coord_t current_ceil_radius = volumes.getRadiusNextCeil(radius, settings.use_min_distance);

            while (current_ceil_radius < target_radius && validWithRadius(volumes.getRadiusNextCeil(current_ceil_radius + 1, settings.use_min_distance)))
                current_ceil_radius = volumes.getRadiusNextCeil(current_ceil_radius + 1, settings.use_min_distance);
            // Catch up the gain to the largest one that stays within the ceiled radius found above and within the drawn radius, and
            // at most one step short of the path without pause (one step less than the distance to the tip). The foot acquired so far
            // is part of both radii.
            current_elem.radius_gain = catch_up_gain(current_elem.radius_gain, current_ceil_radius, support_element_radius(config, current_elem),
                config.min_radius, current_elem.foot_gain, config.path_gain(layer_idx, current_elem.distance_to_top - 1));
        }
        radius = support_element_collision_radius(config, current_elem);

        // The foot of the step: what the step budget bp_gain leaves after the normal growth, up to foot_target. The new collision
        // radius must be valid like the one of any radius increase; when it is not, the foot widens only as far as the cache
        // steps (fine in the foot band, see TreeVolumes::ceilRadius()) allow.
        const double planned_foot_increase = foot_step_gain(config, parent.state, current_elem, layer_idx);
        if (planned_foot_increase > 0.) {
            const double foot_increase = partial_foot_gain(
                double(config.min_radius) + current_elem.radius_gain + current_elem.foot_gain, planned_foot_increase,
                [&](double increase) { return radius_from_gain(config, current_elem.radius_gain, current_elem.foot_gain + increase); },
                [&](coord_t r) { return volumes.getRadiusNextCeil(r, settings.use_min_distance); }, validWithRadius);
            current_elem.foot_gain += foot_increase;
            radius = support_element_collision_radius(config, current_elem);
        }

        if (ceil_radius_before != volumes.ceilRadius(radius, settings.use_min_distance)) {
            if (current_elem.to_buildplate) {
                StoredPolygonCollection to_bp_area = safe_free_area(scratch, increased, volumes.getAvoidance(radius, layer_idx - 1, settings.type, false, settings.use_min_distance));
                to_bp_data.get().move_from(to_bp_area);
            }
            if (config.support_rests_on_model) {
                StoredPolygonCollection to_model_area = safe_free_area(scratch, increased,
                    current_elem.to_model_gracious ?
                        volumes.getAvoidance(radius, layer_idx - 1, settings.type, true, settings.use_min_distance) :
                        volumes.getCollision(radius, layer_idx - 1, settings.use_min_distance));
                to_model_data.get().move_from(to_model_area);
            }
            if (polygons_area(check_layer_data) < tiny_area_threshold) {
                BOOST_LOG_TRIVIAL(error) << "Lost area by doing catch up from " << ceil_radius_before << " to radius " <<
                    volumes.ceilRadius(support_element_collision_radius(config, current_elem), settings.use_min_distance);
                BOOST_LOG_TRIVIAL(error) << "Area lost catching up radius. May not cause visible malformation."sv;
            }
        }
    }

    return polygons_area(check_layer_data) > tiny_area_threshold ? std::optional<SupportElementState>(current_elem) : std::optional<SupportElementState>();
}

/*!
 * \brief Set the result_on_layer point for all influence areas
 *
 * \param move_bounds[in,out] All currently existing influence areas
 * \param context[in] Checked once after layer 0 and after each layer; a cancellation throws PluginCancelled. The placeable areas that
 *        set_to_model_contact_to_model_gracious() reads lazily are interruptible through the context of the volumes.
 */
static void create_nodes_from_area(
    const TreeVolumes       &volumes,
    const TreeSettings    &config,
    std::vector<SupportElements> &move_bounds,
    const plugin_run_context     *context)
{
    // Initialize points on layer 0, with a "random" point in the influence area.
    // Point is chosen based on an inaccurate estimate where the branches will split into two, but every point inside the influence area would produce a valid result.
    {
        SupportElements *layer_above = move_bounds.size() > 1 ? &move_bounds[1] : nullptr;
        if (layer_above) {
            for (SupportElement &elem : *layer_above)
                elem.state.marked = false;
        }
        for (SupportElement &init : move_bounds.front()) {
            init.state.result_on_layer = move_inside_if_outside(init.influence_area, init.state.next_position);
            // Also set the parent nodes, as these will be required for the first iteration of the loop below and mark the parent nodes.
            set_points_on_areas(init, layer_above);
        }
    }

    slic3r_api::throw_if_cancelled(context);

    for (LayerIndex layer_idx = 1; layer_idx < LayerIndex(move_bounds.size()); ++ layer_idx) {
        SupportElements &layer       = move_bounds[layer_idx];
        SupportElements *layer_above = layer_idx + 1 < LayerIndex(move_bounds.size()) ? &move_bounds[layer_idx + 1] : nullptr;
        if (layer_above)
            for (SupportElement &elem : *layer_above)
                elem.state.marked = false;
        for (SupportElement &elem : layer) {
            assert(! elem.state.deleted);
            assert(elem.state.layer_idx == layer_idx);
            // check if the resulting center point is not yet set
            if (! elem.state.result_on_layer_is_set()) {
                // An element without a placement is dropped for one of three reasons: it is to_buildplate (an error: it should have
                // reached the bed); its tip is less than min_height_to_model of real Z above it, so it may not rest on the model;
                // or the support is build plate only and the element is not to_buildplate.
                if (elem.state.to_buildplate || ! config.reaches_min_height_to_model(layer_idx, elem.state.distance_to_top) || ! config.support_rests_on_model) {
                    if (elem.state.to_buildplate) {
                        BOOST_LOG_TRIVIAL(error) << "Uninitialized Influence area targeting " << elem.state.target_position.x << "," << elem.state.target_position.y << ") "
                            "at target_height: " << elem.state.target_height << " layer: " << layer_idx;
                        BOOST_LOG_TRIVIAL(error) << "Uninitialized support element! A branch could be missing or exist partially."sv;
                    }
                    // we dont need to remove yet the parents as they will have a lower dtt and also no result_on_layer set
                    elem.state.deleted = true;
                } else {
                    // set the point where the branch will be placed on the model
                    if (elem.state.to_model_gracious)
                        set_to_model_contact_to_model_gracious(volumes, config, move_bounds, elem);
                    else
                        set_to_model_contact_simple(elem);
                }
            }
            if (! elem.state.deleted && ! elem.state.marked && elem.state.target_height == layer_idx)
                // Just a tip surface with no supporting element.
                elem.state.deleted = true;
            if (elem.state.deleted) {
                for (int32_t parent_idx : elem.parents)
                    // A top element that did not move may already have its result set.
                    // As this branch needs to be removed => all parents result_on_layer have to be invalidated.
                    (*layer_above)[parent_idx].state.result_on_layer_reset();
            }
            if (! elem.state.deleted) {
                // Element is valid now setting points in the layer above and mark the parent nodes.
                set_points_on_areas(elem, layer_above);
            }
        }
        slic3r_api::throw_if_cancelled(context);
    }

    // Verify the tree connectivity including the branch slopes.
    for (LayerIndex layer_idx = 0; layer_idx + 1 < LayerIndex(move_bounds.size()); ++ layer_idx) {
        SupportElements &layer = move_bounds[layer_idx];
        SupportElements &above = move_bounds[layer_idx + 1];
        for (SupportElement &elem : layer)
            if (! elem.state.deleted) {
                for (int32_t iparent : elem.parents) {
                    SupportElement &parent = above[iparent];
                    assert(! parent.state.deleted);
                    assert(elem.state.result_on_layer_is_set() == parent.state.result_on_layer_is_set());
                    if (elem.state.result_on_layer_is_set()) {
                        double radius_increase = support_element_radius(config, elem) - support_element_radius(config, parent);
                        assert(radius_increase >= 0);
                    }
                }
            }
        }

    remove_deleted_elements(move_bounds);

    // Verify the tree connectivity including the branch slopes.
    for (LayerIndex layer_idx = 0; layer_idx + 1 < LayerIndex(move_bounds.size()); ++ layer_idx) {
        SupportElements &layer = move_bounds[layer_idx];
        SupportElements &above = move_bounds[layer_idx + 1];
        for (SupportElement &elem : layer) {
            assert(! elem.state.deleted);
            for (int32_t iparent : elem.parents) {
                SupportElement &parent = above[iparent];
                assert(! parent.state.deleted);
                assert(elem.state.result_on_layer_is_set() == parent.state.result_on_layer_is_set());
                if (elem.state.result_on_layer_is_set()) {
                    double radius_increase = support_element_radius(config, elem) - support_element_radius(config, parent);
                    assert(radius_increase >= 0);
                }
            }
        }
    }
}

/*!
 * \brief Positions the parents of elem, the elements of the layer above that elem carries.
 *
 * elem lies on the lower layer and already has its result_on_layer. Each parent in layer_above that has none yet gets elem's point when it lies inside its
 * influence area, else the closest point of the area (move_inside_if_outside()); a parent whose result_on_layer is already set (a branch that did not move) keeps it. Every
 * parent is marked as reached from a valid child. layer_above is null only when elem has no parents (top layer), and is then not read.
 *
 * \param elem[in] The element whose parents are positioned.
 * \param layer_above[in,out] The elements of the layer above elem; the parents are modified.
 */
static void set_points_on_areas(const SupportElement &elem, SupportElements *layer_above)
{
    assert(!elem.state.deleted);
    assert(layer_above != nullptr || elem.parents.empty());

    // Based on the branch center point of the current layer, the point on the next (further up) layer is calculated.
    if (! elem.state.result_on_layer_is_set()) {
        BOOST_LOG_TRIVIAL(error) << "Uninitialized support element";
        BOOST_LOG_TRIVIAL(error) << "Uninitialized support element. A branch may be missing.\n"sv;
        return;
    }

    if (layer_above)
        for (int32_t next_elem_idx : elem.parents) {
            assert(next_elem_idx >= 0);
            SupportElement &next_elem = (*layer_above)[next_elem_idx];
            assert(! next_elem.state.deleted);
            // Keep a result set earlier: it belongs to a branch that did not move.
            if (! next_elem.state.result_on_layer_is_set()) {
                // Move inside has edgecases (see tests) so DONT use Polygons.inside to confirm correct move, Error with distance 0 is <= 1
                // it is not required to check if how far this move moved a point as is can be larger than maximum_movement_distance.
                // While this seems like a problem it may for example occur after merges.
                next_elem.state.result_on_layer = move_inside_if_outside(next_elem.influence_area, elem.state.result_on_layer);
                // do not call recursive because then amount of layers would be restricted by the stack size
            }
            // Mark the parent element as accessed from a valid child element.
            next_elem.state.marked = true;
        }
}

static void set_to_model_contact_simple(SupportElement &elem)
{
    const c_point best = move_inside_if_outside(elem.influence_area, elem.state.next_position);
    elem.state.result_on_layer = best;
    BOOST_LOG_TRIVIAL(debug) << "Added NON gracious Support On Model Point (" << best.x << "," << best.y << "). The current layer is " << elem.state.layer_idx;
}

/*!
 * \brief Get the best point to connect to the model and set the result_on_layer of the relevant SupportElement accordingly.
 *
 * Starting at first_elem, walks up the parents (one layer per step, as long as the element has a single parent) while the influence
 * area of the element still meets the placeable area of its radius; the last element that does is the last valid placement. The
 * elements below it are then removed and it gets its point. When even first_elem has no valid placement, it is placed with the
 * simple placement instead, and a warning is logged. The placeable areas are read from the volumes, whose lazy computations check
 * the cancellation of their context: a cancellation propagates from here as PluginCancelled.
 *
 * \param move_bounds[in,out] All currently existing influence areas
 * \param first_elem[in,out] SupportElement that did not have its result_on_layer set meaning that it does not have a child element.
 */
static void set_to_model_contact_to_model_gracious(
    const TreeVolumes          &volumes,
    const TreeSettings       &config,
    std::vector<SupportElements>    &move_bounds,
    SupportElement                  &first_elem)
{
    SupportElement *last_successfull_layer = nullptr;

    // check for every layer upwards, up to the point where this influence area was created (either by initial insert or merge) if the branch could be placed on it, and highest up layer index.
    // The common part with the placeable area is a temporary of the check, in a scratch storage.
    with_scratch_storage([&](storage_handle *scratch) {
        SupportElement *elem = &first_elem;
        for (LayerIndex layer_check = elem->state.layer_idx;
            ! polygons_intersection(scratch, elem->influence_area, volumes.getPlaceableAreas(support_element_collision_radius(config, elem->state), layer_check)).empty();
            elem = &move_bounds[++ layer_check][elem->parents.front()]) {
            assert(elem->state.layer_idx == layer_check);
            assert(! elem->state.deleted);
            assert(elem->state.to_model_gracious);
            last_successfull_layer = elem;
            if (elem->parents.size() != 1)
                // Reached merge point.
                break;
        }
    });

    // Could not find valid placement, even though it should exist => error handling
    if (last_successfull_layer == nullptr) {
        BOOST_LOG_TRIVIAL(warning) << "No valid placement found for to model gracious element on layer " << first_elem.state.layer_idx;
        BOOST_LOG_TRIVIAL(error) << "Could not fine valid placement on model! Just placing it down anyway. Could cause floating branches."sv;
        first_elem.state.to_model_gracious = false;
        set_to_model_contact_simple(first_elem);
    } else {
        // Found a gracious area above first_elem. Remove all below last_successfull_layer.
        {
            LayerIndex parent_layer_idx = first_elem.state.layer_idx;
            for (SupportElement *elem = &first_elem; elem != last_successfull_layer; elem = &move_bounds[++ parent_layer_idx][elem->parents.front()]) {
                assert(! elem->state.deleted);
                elem->state.deleted = true;
            }
        }
        // Guess a point inside the influence area, in which the branch will be placed in.
        const c_point best = move_inside_if_outside(last_successfull_layer->influence_area, last_successfull_layer->state.next_position);
        last_successfull_layer->state.result_on_layer = best;
        BOOST_LOG_TRIVIAL(debug) << "Added gracious Support On Model Point (" << best.x << "," << best.y << "). The current layer is " << last_successfull_layer;
    }
}

// Remove elements marked as "deleted", update indices to parents.
static void remove_deleted_elements(std::vector<SupportElements> &move_bounds)
{
    std::vector<int32_t> map_parents;
    std::vector<int32_t> map_current;
    for (LayerIndex layer_idx = LayerIndex(move_bounds.size()) - 1; layer_idx >= 0; -- layer_idx) {
        SupportElements &layer = move_bounds[layer_idx];
        map_current.clear();
        for (int32_t i = 0; i < int32_t(layer.size());) {
            SupportElement &element = layer[i];
            if (element.state.deleted) {
                if (map_current.empty()) {
                    // Initialize with identity map.
                    map_current.assign(layer.size(), 0);
                    std::iota(map_current.begin(), map_current.end(), 0);
                }
                // Delete all "deleted" elements from the end of the layer vector.
                while (i < int32_t(layer.size()) && layer.back().state.deleted) {
                    layer.pop_back();
                    // Mark as deleted in the map.
                    map_current[layer.size()] = -1;
                }
                assert(i == layer.size() || i + 1 < layer.size());
                if (i + 1 < int32_t(layer.size())) {
                    element = std::move(layer.back());
                    layer.pop_back();
                    // Mark the current element as deleted.
                    map_current[i] = -1;
                    // Mark the moved element as moved to index i.
                    map_current[layer.size()] = i;
                }
            } else {
                // Current element is not deleted. Update its parent indices.
                if (! map_parents.empty())
                    for (int32_t &parent_idx : element.parents)
                        parent_idx = map_parents[parent_idx];
                ++ i;
            }
        }
        std::swap(map_current, map_parents);
    }
}

// Turns the placed elements into routed trees. Elements linked through their parents belong to the same tree; the trees are
// built from the top layer down, so each node finds its carried nodes already in place.
static std::vector<RoutedTree> build_trees(const slic3r_api::Object &object, const TreeSettings &config, const std::vector<SupportElements> &move_bounds)
{
    constexpr size_t none = std::numeric_limits<size_t>::max();
    // Elements of all layers get one flat index: the layer offset plus the index in the layer.
    std::vector<size_t> first_index(move_bounds.size() + 1, 0);
    for (size_t layer_idx = 0; layer_idx < move_bounds.size(); ++ layer_idx)
        first_index[layer_idx + 1] = first_index[layer_idx] + move_bounds[layer_idx].size();
    std::vector<size_t> forest(first_index.back());
    std::iota(forest.begin(), forest.end(), size_t(0));
    for (size_t layer_idx = 0; layer_idx + 1 < move_bounds.size(); ++ layer_idx)
        for (size_t idx = 0; idx < move_bounds[layer_idx].size(); ++ idx) {
            const SupportElement &elem = move_bounds[layer_idx][idx];
            if (! elem.state.result_on_layer_is_set())
                continue;
            for (int32_t parent : elem.parents) {
                if (! move_bounds[layer_idx + 1][parent].state.result_on_layer_is_set())
                    continue;
                const size_t root = find_root(forest, first_index[layer_idx] + idx);
                const size_t parent_root = find_root(forest, first_index[layer_idx + 1] + size_t(parent));
                if (root != parent_root)
                    forest[root] = parent_root;
            }
        }

    std::vector<RoutedTree> trees;
    std::vector<size_t> tree_of_root(first_index.back(), none);
    std::vector<size_t> local_index(first_index.back(), none);
    for (size_t layer_idx = move_bounds.size(); layer_idx -- > 0; )
        for (size_t idx = 0; idx < move_bounds[layer_idx].size(); ++ idx) {
            const SupportElement &elem = move_bounds[layer_idx][idx];
            if (! elem.state.result_on_layer_is_set())
                continue;
            const size_t root = find_root(forest, first_index[layer_idx] + idx);
            if (tree_of_root[root] == none) {
                tree_of_root[root] = trees.size();
                trees.emplace_back();
            }
            RoutedTree &tree = trees[tree_of_root[root]];
            TreeNode node;
            node.layer = layer_idx;
            node.print_z = unscaled(object.layer(uint32_t(layer_idx)).print_z());
            node.position = elem.state.result_on_layer;
            node.radius = support_element_radius(config, elem);
            node.to_buildplate = elem.state.to_buildplate;
            node.to_model_gracious = elem.state.to_model_gracious;
            node.lost = elem.state.lost;
            node.verylost = elem.state.verylost;
            for (int32_t parent : elem.parents)
                if (const size_t carried = local_index[first_index[layer_idx + 1] + size_t(parent)]; carried != none)
                    node.carries.push_back(carried);
            local_index[first_index[layer_idx] + idx] = tree.nodes.size();
            tree.nodes.push_back(std::move(node));
        }
    return trees;
}

// Find the representative of an element in the union-find forest, halving the path on the way.
static size_t find_root(std::vector<size_t> &forest, size_t idx)
{
    while (forest[idx] != idx) {
        forest[idx] = forest[forest[idx]];
        idx = forest[idx];
    }
    return idx;
}

std::vector<size_t> nodes_below(const RoutedTree &tree)
{
    std::vector<size_t> below(tree.nodes.size(), no_node);
    for (size_t idx = 0; idx < tree.nodes.size(); ++idx)
        for (const size_t upper : tree.nodes[idx].carries) {
            assert(below[upper] == no_node);
            below[upper] = idx;
        }
    return below;
}

