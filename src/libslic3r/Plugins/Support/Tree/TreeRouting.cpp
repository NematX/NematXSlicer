// A temporary collection of a scratch storage that is allocated at its first use: most elements of the increase step never need some
// of their candidate areas, and every collection costs a storage allocation. It must not outlive the scratch storage it was given.
class LazyPolygons {
public:
    explicit LazyPolygons(storage_handle *scratch) : m_scratch(scratch) {}
    // The collection, allocated when it is asked for the first time.
    StoredPolygonCollection &get()
    {
        if (! m_collection)
            m_collection.emplace(m_scratch);
        return *m_collection;
    }
    // Whether no ring has been stored (a collection that was never asked for holds none).
    bool empty() const { return ! m_collection || m_collection->empty(); }
    // The signed area of the rings, 0 for a collection that was never asked for.
    double area() const { return m_collection ? polygons_area(*m_collection) : 0.; }

private:
    storage_handle *m_scratch;
    std::optional<StoredPolygonCollection> m_collection;
};

