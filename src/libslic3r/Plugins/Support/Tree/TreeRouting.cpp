/* Routing of the tree branches of one object: tips, influence areas propagated down the object layers, and nodes.

   The routing runs once per object, in this order:
   1. route_trees() adds the top contacts that the island support demand asks for, through the shared helper
      (Common/SupportZPlacement.hpp), and lists the tip sources: the contact area and the object layer where its tips start.
   2. TreeVolumes precalculates the collision, avoidance and placeable areas of the object layers.
   3. generate_initial_areas() samples the tips under each contact and creates one influence area per tip. The tip
      sampling lines are the lines of the base pattern of the support, generated by the INFILL_PATTERN plugin through
      the pattern callbacks of the STEP_SUPPORT payload (Common/PatternService.hpp).
   4. create_layer_pathing() moves every influence area one object layer down at a time, within the maximum move of
      the layer, and merges the areas that come to overlap.
   5. create_nodes_from_area() chooses the point each influence area is drawn through.
   6. build_trees() connects the placed elements through their parents into routed trees.

   The whole file is written on the plugin API (views, storage-owned collections, the TreeGeometry.hpp helpers, c_point states and node
   positions). The influence areas are StoredPolygonCollections (TreeElements.hpp); steps 4 and 5 find the point of an area with
   move_inside_if_outside() (TreeGeometry.hpp), which keeps the native distance tie rule.

   Storage: a tip source is a job of its own; its temporary collections live in the scratch storage of the job, which the
   host destroys when the job ends. The areas that outlive a function (the contact areas of the tip sources, the influence
   areas of the elements) live in the storage of the support. In step 4 the data of the merge of one layer (the three
   candidate areas of each element) must outlive the jobs that fill them but not the layer: it lives in a scratch storage of
   create_layer_pathing(), which the jobs of the layer share; each job keeps its own temporaries in its own scratch storage
   and moves the areas that stay into the collections of the layer (rings move, handles do not). When a layer is finished,
   the areas that remain are moved into new collections of the run storage. The elements (SupportElements) are local data of
   route_trees(): their collections are freed when route_trees() returns, before the run storage, and the returned trees hold
   no handle.

   The code is a port of the legacy tree support (Support/TreeSupport.cpp) onto the plugin API. Drawing, roofs, rafts
   and organic branches are not part of it. The tips start under the top interface stack, and the influence areas use
   the real height of each layer for their maximum move.
*/

