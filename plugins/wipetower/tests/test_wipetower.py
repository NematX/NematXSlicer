# The line that gives the export time.
IGNORED_PREFIXES = ("; generated by ",)
# Host message when a loaded profile names a manager that is not available: the default one is used instead.
REFUSED_SELECTION = 'key = "step_wipetower_plugin"'


def two_extruder_options() -> tuple[str, ...]:
    """The settings of a printer with two extruders: the host defaults of the per-extruder settings, twice."""
    case_dir = OUTPUT_ROOT / "defaults-saved"
    case_dir.mkdir(parents=True, exist_ok=True)
    (case_dir / "profile.ini").write_text(BASE_PROFILE[0] + "\n", encoding="utf-8")
    saved = case_dir / "defaults.ini"
    subprocess.run([str(HOST_EXECUTABLE), "--datadir", str(PLUGIN_DATADIR), "--load", str(case_dir / "profile.ini"),
                    "--save", str(saved)], capture_output=True, timeout=600, env=host_environment(), check=True)
    defaults = dict(line.split(" = ", 1) for line in saved.read_text(encoding="utf-8").splitlines() if " = " in line)
    options = []
    for key in EXTRUDER_KEYS:
        # String vectors are separated by ';', the other vectors by ','.
        separator = ";" if defaults[key].startswith('"') else ","
        options.append(f"{key} = {defaults[key]}{separator}{defaults[key]}")
    return tuple(options) + ("nozzle_diameter = 0.4,0.4", "filament_diameter = 1.75,1.75", "temperature = 210,210",
                             "first_layer_temperature = 210,210")


def write_two_parts(path: Path) -> None:
    """Two 10 x 10 x 3 mm boxes, 10 mm apart, printed by extruders 1 and 2: one tool change per layer."""
    write_boxes(path, [(0, 0, 0, 10, 10, 3, 1), (20, 0, 0, 30, 10, 3, 2)])


def write_boxes(path: Path, boxes: list[tuple[float, float, float, float, float, float, int]]) -> None:
    """One object made of box volumes (x0, y0, z0, x1, y1, z1, extruder)."""
    faces = ((3, 2, 1), (1, 0, 3), (4, 5, 6), (6, 7, 4), (0, 1, 5), (5, 4, 0),
             (1, 2, 6), (6, 5, 1), (2, 3, 7), (7, 6, 2), (3, 0, 4), (4, 7, 3))
    vertices, triangles, config = [], [], ""
    for index, (x0, y0, z0, x1, y1, z1, extruder) in enumerate(boxes):
        base, first = len(vertices), len(triangles)
        vertices += [(x, y, z) for z in (z0, z1) for x, y in ((x0, y0), (x1, y0), (x1, y1), (x0, y1))]
        triangles += [tuple(base + corner for corner in face) for face in faces]
        config += (f'<volume firstid="{first}" lastid="{len(triangles) - 1}">'
                   f'<metadata type="volume" key="name" value="part-{index}" />'
                   '<metadata type="volume" key="volume_type" value="ModelPart" />'
                   f'<metadata type="volume" key="extruder" value="{extruder}" /></volume>')
    model = ('<?xml version="1.0" encoding="UTF-8"?><model unit="millimeter" xml:lang="en-US" '
             'xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02"><resources>'
             '<object id="1" type="model"><mesh><vertices>'
             + "".join(f'<vertex x="{x:g}" y="{y:g}" z="{z:g}" />' for x, y, z in vertices) + "</vertices><triangles>"
             + "".join(f'<triangle v1="{a}" v2="{b}" v3="{c}" />' for a, b, c in triangles)
             + '</triangles></mesh></object></resources><build><item objectid="1" /></build></model>')
    with ZipFile(path, "w", ZIP_DEFLATED) as archive:
        archive.writestr("[Content_Types].xml",
                         '<?xml version="1.0" encoding="UTF-8"?>'
                         '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
                         '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml" />'
                         '<Default Extension="model" ContentType="application/vnd.ms-package.3dmanufacturing-3dmodel+xml" />'
                         '<Override PartName="/Metadata/Slic3r_PE_model.config" ContentType="application/xml" /></Types>')
        archive.writestr("_rels/.rels",
                         '<?xml version="1.0" encoding="UTF-8"?>'
                         '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
                         '<Relationship Target="/3D/3dmodel.model" Id="rel0" '
                         'Type="http://schemas.microsoft.com/3dmanufacturing/2013/01/3dmodel" /></Relationships>')
        archive.writestr("3D/3dmodel.model", model)
        archive.writestr("Metadata/Slic3r_PE_model.config",
                         f'<?xml version="1.0" encoding="UTF-8"?><config><object id="1">{config}</object></config>')


def host_environment() -> dict[str, str]:
    environment = dict(os.environ)
    environment["PATH"] = os.pathsep.join(RUNTIME_PATH + [environment.get("PATH", "")])
    return environment


def run_export(name: str, options: tuple[str, ...], model: Path, datadir: Path | None = None) -> tuple[str, str]:
    """Exports `model` with the base profile and the options; returns the G-code text and the host log."""
    case_dir = OUTPUT_ROOT / name
    case_dir.mkdir(parents=True, exist_ok=True)
    profile = case_dir / "profile.ini"
    output = case_dir / "result.gcode"
    # A later option replaces an earlier one with the same key.
    merged = {option.split("=", 1)[0].strip(): option for option in BASE_PROFILE + options}
    profile.write_text("\n".join(merged.values()) + "\n", encoding="utf-8")
    output.unlink(missing_ok=True)
    # The datadir must be a native absolute path: the Debug host checks it.
    result = subprocess.run([str(HOST_EXECUTABLE), "--datadir", str(datadir or PLUGIN_DATADIR), "--export-gcode", "--load",
                             str(profile), "--output", str(output), str(model)],
                            capture_output=True, timeout=1800, env=host_environment())
    log = (result.stdout + result.stderr).decode("utf-8", errors="replace")
    (case_dir / "host.log").write_text(log, encoding="utf-8")
    if result.returncode != 0 or not output.is_file():
        raise AssertionError(f"{name}: export failed (exit {result.returncode}); see {case_dir / 'host.log'}")
    for message in ("will be disabled", "unknown option"):
        if message in log.lower():
            raise AssertionError(f"{name}: {message!r} in {case_dir / 'host.log'}")
    # Errors of other plugin groups are reported by their own packages' tests. The datadir path contains
    # "wipetower", so only the words of a wipe tower message are looked for.
    for line in log.splitlines():
        if "[error]" in line and ("wipe tower" in line.lower() or "wipe_tower" in line.lower()):
            raise AssertionError(f"{name}: wipe tower error in {case_dir / 'host.log'}: {line}")
    return output.read_text(encoding="utf-8", errors="replace"), log


def comparable_lines(gcode: str) -> list[str]:
    return [line for line in gcode.splitlines() if not line.startswith(IGNORED_PREFIXES)]


Segment = tuple[tuple[float, float], tuple[float, float]]
WORD = re.compile(r"([XYEZ])([+-]?(?:\d+(?:\.\d*)?|\.\d+))")


def tower_segments_by_tool(gcode: str) -> dict[tuple[float, int], set[Segment]]:
    """Extruding XY segments of the wipe tower role, by layer Z (;Z: marker) and tool (Tn command)."""
    layers: dict[tuple[float, int], set[Segment]] = {}
    x = y = e = z = 0.0
    tool = 0
    relative_e = False
    role = ""
    for line in gcode.splitlines():
        if line.startswith(";TYPE:"):
            role = line[6:]
        elif line.startswith(";Z:"):
            z = float(line[3:])
        elif re.fullmatch(r"T\d+", line.strip()):
            tool = int(line.strip()[1:])
        elif line.startswith("M83"):
            relative_e = True
        elif line.startswith("M82"):
            relative_e = False
        elif line.startswith("G92"):
            words = dict(WORD.findall(line))
            if "E" in words:
                e = float(words["E"])
        elif line.startswith(("G0 ", "G1 ")):
            words = {key: float(value) for key, value in WORD.findall(line.split(";", 1)[0])}
            nx, ny = words.get("X", x), words.get("Y", y)
            extruded = words.get("E", 0.0 if relative_e else e)
            deposited = extruded if relative_e else extruded - e
            if not relative_e:
                e = extruded
            if deposited > 0 and (nx, ny) != (x, y) and role == "Wipe tower":
                segment = tuple(sorted(((round(x, 3), round(y, 3)), (round(nx, 3), round(ny, 3)))))
                layers.setdefault((z, tool), set()).add(segment)
            x, y = nx, ny
    return layers


def tower_segments(gcode: str) -> dict[float, set[Segment]]:
    """Extruding XY segments of the wipe tower role, by layer Z, whatever the tool."""
    layers: dict[float, set[Segment]] = {}
    for (z, _), segments in tower_segments_by_tool(gcode).items():
        layers.setdefault(z, set()).update(segments)
    return layers


def tower_y_by_tool(gcode: str) -> dict[float, dict[int, tuple[float, float]]]:
    """Y extent of the extruding wipe tower segments of each tool, by layer Z."""
    extents: dict[float, dict[int, tuple[float, float]]] = {}
    for (z, tool), segments in tower_segments_by_tool(gcode).items():
        ys = [point[1] for segment in segments for point in segment]
        extents.setdefault(z, {})[tool] = (min(ys), max(ys))
    return extents

def bounding_box(segments: set[Segment]) -> tuple[float, float, float, float]:
    xs = [point[0] for segment in segments for point in segment]
    ys = [point[1] for segment in segments for point in segment]
    return min(xs), min(ys), max(xs), max(ys)


class WipeTowerParity(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        plugin = PLUGIN_DATADIR / "plugins" / "nematx-wipetower" / ("plugin.dll" if sys.platform == "win32" else "plugin.so")
        for required in (HOST_EXECUTABLE, plugin):
            if not required.is_file():
                raise FileNotFoundError(f"Missing build or staged package input: {required}")
        shutil.rmtree(OUTPUT_ROOT, ignore_errors=True)
        OUTPUT_ROOT.mkdir(parents=True, exist_ok=True)
        cls.model = OUTPUT_ROOT / "two-parts.3mf"
        write_two_parts(cls.model)
        cls.extruders = two_extruder_options()

    def export_both(self, name: str, options: tuple[str, ...]) -> tuple[str, str]:
        options = self.extruders + options
        default, _ = run_export(f"{name}-default", options + (f"step_wipetower_plugin = {DEFAULT_MANAGER}",), self.model)
        nematx, log = run_export(f"{name}-nematx", options + (f"step_wipetower_plugin = {NEMATX_MANAGER}",), self.model)
        self.assertNotIn(REFUSED_SELECTION, log, f"{name}: the NematX manager was not selected")
        return default, nematx

    def test_parity_with_the_default_manager(self) -> None:
        for name, options in PARITY_CASES.items():
            with self.subTest(case=name):
                default, nematx = self.export_both(name, options)
                # The tower must exist, otherwise the comparison proves nothing.
                self.assertIn(";TYPE:Wipe tower", default)
                expected, actual = comparable_lines(default), comparable_lines(nematx)
                if expected != actual:
                    diff = "\n".join(list(difflib.unified_diff(expected, actual, "default", "nematx", lineterm="", n=2))[:40])
                    self.fail(f"{name}: the G-code differs from the default manager:\n{diff}")

    def test_perimeters_add_or_remove_loops(self) -> None:
        # Compare one layer above the first one, which has no brim: three perimeters keep every default
        # segment and add two loops outside; zero perimeters remove the band rectangle and nothing else.
        default, _ = run_export("perimeters-default", self.extruders + (f"step_wipetower_plugin = {DEFAULT_MANAGER}",), self.model)
        three, _ = run_export("perimeters-three", self.extruders + (f"step_wipetower_plugin = {NEMATX_MANAGER}",
                                                                   "wipe_tower_perimeters = 3"), self.model)
        none, _ = run_export("perimeters-zero", self.extruders + (f"step_wipetower_plugin = {NEMATX_MANAGER}",
                                                                 "wipe_tower_perimeters = 0"), self.model)
        default_layers, three_layers, none_layers = tower_segments(default), tower_segments(three), tower_segments(none)
        z = sorted(default_layers)[2]
        reference, wider, bare = default_layers[z], three_layers[z], none_layers[z]
        self.assertTrue(reference <= wider)
        x0, y0, x1, y1 = bounding_box(reference)
        wx0, wy0, wx1, wy1 = bounding_box(wider)
        # Two further loops at one and two line spacings: the 0.6 mm tower line has a 0.557 mm spacing at 0.2 mm.
        spacing = 0.6 - 0.2 * (1 - math.pi / 4)
        for inner, outer in ((x0, wx0), (y0, wy0), (-x1, -wx1), (-y1, -wy1)):
            self.assertAlmostEqual(inner - outer, 2 * spacing, delta=0.01)
        self.assertTrue(bare <= reference)
        # The first purge line runs on the bottom side of the rectangle, so only the other sides disappear.
        sides = {((x0, y0), (x1, y0)), ((x1, y0), (x1, y1)), ((x0, y1), (x1, y1)), ((x0, y0), (x0, y1))}
        self.assertTrue(sides - bare)
        self.assertEqual(reference - bare, sides - bare)

    def check_separate_sections(self, gcode: str, tools: set[int]) -> None:
        """Every tower layer above the first one has a section of each tool; sections never overlap and keep
        their place. The first layer is skipped: its brim, printed by one tool, surrounds every section."""
        extents = tower_y_by_tool(gcode)
        layers = sorted(extents)[1:]
        self.assertTrue(layers)
        places: dict[int, tuple[float, float]] = {}
        for z in layers:
            self.assertEqual(tools, set(extents[z]), f"tools of the tower layer at z={z}")
            ranges = sorted(extents[z].values())
            for (_, high), (low, _) in zip(ranges, ranges[1:]):
                self.assertLess(high, low, f"sections overlap at z={z}")
            for tool, extent in extents[z].items():
                expected = places.setdefault(tool, extent)
                self.assertAlmostEqual(expected[0], extent[0], delta=0.01, msg=f"tool {tool} moves at z={z}")
                self.assertAlmostEqual(expected[1], extent[1], delta=0.01, msg=f"tool {tool} moves at z={z}")

    def test_separate_sections_keep_each_filament_apart(self) -> None:
        gcode, _ = run_export("separate", self.extruders + (f"step_wipetower_plugin = {NEMATX_MANAGER}",
                                                           "wipe_tower_separate_filament = 1"), self.model)
        self.check_separate_sections(gcode, {0, 1})

    def test_separate_sections_are_printed_where_their_tool_is_absent(self) -> None:
        # Tool 1 prints the bottom and top blocks, tool 2 the middle one: each tool is absent from the
        # tower owner's layers for a while, and still prints its section there.
        stacked = OUTPUT_ROOT / "stacked.3mf"
        write_boxes(stacked, [(0, 0, 0, 10, 10, 1, 1), (0, 0, 1, 10, 10, 2, 2), (0, 0, 2, 10, 10, 3, 1)])
        gcode, _ = run_export("separate-stacked", self.extruders + (f"step_wipetower_plugin = {NEMATX_MANAGER}",
                                                                   "wipe_tower_separate_filament = 1"), stacked)
        self.check_separate_sections(gcode, {0, 1})

    def test_separate_sections_are_refused_with_one_nozzle(self) -> None:
        case_options = self.extruders + (f"step_wipetower_plugin = {NEMATX_MANAGER}", "wipe_tower_separate_filament = 1",
                                         "single_extruder_multi_material = 1")
        with self.assertRaises(AssertionError):
            run_export("separate-semm", case_options, self.model)
        log = (OUTPUT_ROOT / "separate-semm" / "host.log").read_text(encoding="utf-8")
        self.assertIn("Separate filament sections of the wipe tower cannot be used", log)

    def check_dense_fill(self, sparse: str, dense: str) -> None:
        """Above the first layer, the only segments that change are the fill of the unused area, and the dense
        fill is much longer than the sparse grid (a tenth of the area by default). The first layer is always
        dense; a layer whose bands use the whole depth has no fill."""
        sparse_layers, dense_layers = tower_segments(sparse), tower_segments(dense)
        self.assertEqual(sorted(sparse_layers), sorted(dense_layers))
        self.assertEqual(sparse_layers[min(sparse_layers)], dense_layers[min(dense_layers)])
        changed = 0
        for z in sorted(sparse_layers)[1:]:
            grid = sparse_layers[z] - dense_layers[z]
            solid = dense_layers[z] - sparse_layers[z]
            if not grid and not solid:
                continue
            changed += 1
            grid_length = sum(math.dist(*segment) for segment in grid)
            solid_length = sum(math.dist(*segment) for segment in solid)
            self.assertGreater(solid_length, 4 * grid_length, f"fill at z={z}")
        self.assertGreater(changed, 0)

    def test_only_solid_fills_every_layer_densely(self) -> None:
        # The stacked blocks change tools on a few layers only, so the tower has layers with unused area.
        stacked = OUTPUT_ROOT / "stacked-solid.3mf"
        write_boxes(stacked, [(0, 0, 0, 10, 10, 1, 1), (0, 0, 1, 10, 10, 2, 2), (0, 0, 2, 10, 10, 3, 1)])
        nematx = (f"step_wipetower_plugin = {NEMATX_MANAGER}",)
        for name, options in (("shared", ()), ("separate", ("wipe_tower_separate_filament = 1",))):
            with self.subTest(mode=name):
                sparse, _ = run_export(f"only-solid-{name}-off", self.extruders + nematx + options, stacked)
                dense, _ = run_export(f"only-solid-{name}-on", self.extruders + nematx + options +
                                      ("wipe_tower_only_solid = 1",), stacked)
                self.check_dense_fill(sparse, dense)
                if options:
                    self.check_separate_sections(dense, {0, 1})

    def test_selection_needs_the_active_package(self) -> None:
        # The proof of selection used above: with the package deactivated, the host reports the profile value.
        datadir = OUTPUT_ROOT / "datadir-without-package"
        shutil.rmtree(datadir, ignore_errors=True)
        shutil.copytree(PLUGIN_DATADIR, datadir)
        activation = datadir / "plugins" / "activated.ini"
        text = activation.read_text(encoding="utf-8")
        self.assertIn(f"{NEMATX_MANAGER} = 1", text)
        activation.write_text(text.replace(f"{NEMATX_MANAGER} = 1", f"{NEMATX_MANAGER} = 0"), encoding="utf-8")
        _, log = run_export("without-package", self.extruders + (f"step_wipetower_plugin = {NEMATX_MANAGER}",),
                            self.model, datadir)
        self.assertIn(REFUSED_SELECTION, log)

    def test_export_is_deterministic(self) -> None:
        first, _ = run_export("deterministic-1", self.extruders + (f"step_wipetower_plugin = {NEMATX_MANAGER}",), self.model)
        second, _ = run_export("deterministic-2", self.extruders + (f"step_wipetower_plugin = {NEMATX_MANAGER}",), self.model)
        self.assertEqual(comparable_lines(first), comparable_lines(second))


