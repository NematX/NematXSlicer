"""End-to-end checks of the NematX wipe tower manager (step_wipetower_plugin = nematx_wipetower).

Each case exports a generated two-tool model through the host executable twice:
with the host's default manager and with the NematX manager. Without a NematX
setting, both must write the same G-code, apart from the line that names the
selected manager and the generation date. The cases vary one tower setting at a
time from a working two-tool profile.
"""

